// Package earlydata 提供 QUIC（TLS 1.3）握手路径调用的 0-RTT 早期数据准入控制。
//
// 准入规则（对应 RFC 8446 第 8.3 节与 RFC 9001 的抗重放要求）：
//   - 会话票据携带签发时间与 ticket_age_add，服务端按实测票龄重新计算
//     混淆票龄，与客户端在 ClientHello 中携带的混淆票龄比较；
//   - 票龄偏差超出调用方给定窗口，或票龄达到 2^32 毫秒导致 32 位回绕错位时，
//     拒绝 0-RTT；
//   - PSK binder 已存在于集群共享的重放记录中时，拒绝 0-RTT；
//   - 重放记录库不可用时同样拒绝；只有记录写入成功才放行。
//
// 任何拒绝都表示退回 1-RTT 完成握手，而不是断开连接：握手路径应当忽略
// （缓冲或丢弃）早期数据，继续完成普通握手，不得发送连接关闭告警。
//
// 跨节点防重放要求 ReplayStore 的实现由整个集群共享（例如 Redis、分布式
// KV 或数据库）。内存实现 MemoryStore 仅适用于单节点与测试场景。
