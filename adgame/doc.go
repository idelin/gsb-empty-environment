// Package adgame 实现隔离演练平台使用的有限回合攻防博弈。
//
// 博弈要素:
//   - 状态是至多 16 个布尔事实的集合, 用 16 位位图表示。
//   - 攻方与守方轮流执行“满足前置条件”的增 (Add) 删 (Delete) 动作。
//   - 守方动作带非负整数成本, 受整数预算约束; 攻方动作无成本。
//   - 一个回合包含攻方半步与守方半步; 攻方先手 (可配置)。
//   - 任一半步之后目标事实集合成立则攻方立即获胜; 撑过全部回合则守方保证成功。
//
// 求解器对 (状态, 剩余半步, 剩余预算, 行棋方) 做记忆化极小极大递归,
// 输出带完整分支的策略 DAG: 攻方节点展开全部合法动作, 守方节点展开全部
// 可保住胜利的防护动作并确定性地选出一个策略动作; 若守方无法保证目标安全,
// 同一结构给出攻方反策略 (守方节点全分支、攻方节点选必胜动作)。
// 求解结果绝不会用单条最低成本路径代替完整策略树。
//
// 验证器 (verify.go) 基于可达状态上的包含极小模型穷举, 给出动作失效
// (前置不满足 / 生效但无变化 / 预算阻断)、无合法动作与预算耗尽的极小
// 事实集见证, 并提供独立的策略树回放校验与最小 Horn 闭包证书。
