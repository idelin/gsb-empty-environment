// Package typeset computes a sound, path-sensitive set of virtual-call
// targets for a C++-like class hierarchy.
//
// The package models object allocation sites, upcasts, field assignments and
// virtual calls.  Subobjects are identified by their complete inheritance
// path, so repeated non-virtual bases stay distinct.  A virtual base is one
// shared subobject and its virtual slot is resolved across every branch of the
// most-derived object.
package typeset

import (
	"errors"
	"fmt"
)

// Base describes one direct base-class edge.
//
// Name is accepted as an alias for Class.  A virtual edge makes the base
// subobject shared by every path in the complete object.
type Base struct {
	Class   string `json:"class" yaml:"class"`
	Name    string `json:"name,omitempty" yaml:"name,omitempty"`
	Virtual bool   `json:"virtual,omitempty" yaml:"virtual,omitempty"`
}

// Method describes a member function.
//
// Methods are virtual by default because this package is intended for virtual
// dispatch analysis.  Set NonVirtual (or Kind to "nonvirtual") to model a
// statically bound member function.  Signature, when present, is the method
// identity; otherwise Name is the identity.
type Method struct {
	Name       string `json:"name" yaml:"name"`
	Signature  string `json:"signature,omitempty" yaml:"signature,omitempty"`
	Virtual    bool   `json:"virtual,omitempty" yaml:"virtual,omitempty"`
	NonVirtual bool   `json:"non_virtual,omitempty" yaml:"non_virtual,omitempty"`
	Static     bool   `json:"static,omitempty" yaml:"static,omitempty"`
	Kind       string `json:"kind,omitempty" yaml:"kind,omitempty"`
}

// Field describes a data member declared by a class.
type Field struct {
	Name string `json:"name" yaml:"name"`
	Type string `json:"type,omitempty" yaml:"type,omitempty"`
}

// Class is one node in the inheritance graph.
//
// BaseClasses is an input-compatibility alias for Bases.  If both are
// populated, Bases is used.
type Class struct {
	Name        string   `json:"name" yaml:"name"`
	Bases       []Base   `json:"bases,omitempty" yaml:"bases,omitempty"`
	BaseClasses []Base   `json:"base_classes,omitempty" yaml:"base_classes,omitempty"`
	Methods     []Method `json:"methods,omitempty" yaml:"methods,omitempty"`
	Fields      []Field  `json:"fields,omitempty" yaml:"fields,omitempty"`
}

// Allocation is one object allocation site.
//
// Class is the allocated dynamic type.  Type is accepted as an alias.  ID and
// Site are copied into every provenance record; an empty ID is generated by
// the analyzer.
type Allocation struct {
	ID       string              `json:"id" yaml:"id"`
	Name     string              `json:"name,omitempty" yaml:"name,omitempty"`
	Class    string              `json:"class" yaml:"class"`
	Type     string              `json:"type,omitempty" yaml:"type,omitempty"`
	Site     string              `json:"site,omitempty" yaml:"site,omitempty"`
	Location string              `json:"location,omitempty" yaml:"location,omitempty"`
	Source   string              `json:"source,omitempty" yaml:"source,omitempty"`
	Fields   map[string][]string `json:"fields,omitempty" yaml:"fields,omitempty"`
}

// Upcast converts a value to a base-class view.
//
// From, Object, Source and Value are aliases for the source value.  To,
// Target and Type are aliases for the destination static class.  If the source
// is a class name rather than a value ID, the cast applies to every value of
// that static class.  Path optionally selects one inheritance path when the
// destination occurs more than once.
type Upcast struct {
	ID          string   `json:"id" yaml:"id"`
	From        string   `json:"from,omitempty" yaml:"from,omitempty"`
	Object      string   `json:"object,omitempty" yaml:"object,omitempty"`
	Source      string   `json:"source,omitempty" yaml:"source,omitempty"`
	Value       string   `json:"value,omitempty" yaml:"value,omitempty"`
	To          string   `json:"to,omitempty" yaml:"to,omitempty"`
	Target      string   `json:"target,omitempty" yaml:"target,omitempty"`
	Type        string   `json:"type,omitempty" yaml:"type,omitempty"`
	Dest        string   `json:"dest,omitempty" yaml:"dest,omitempty"`
	Destination string   `json:"destination,omitempty" yaml:"destination,omitempty"`
	Path        []string `json:"path,omitempty" yaml:"path,omitempty"`
	PathString  string   `json:"path_string,omitempty" yaml:"path_string,omitempty"`
	Site        string   `json:"site,omitempty" yaml:"site,omitempty"`
}

// FieldAssignment stores Value into Field of Object.
//
// Object, Receiver and Target select the destination object value.  Class
// selects all objects of a static class when no object value is given.  Value,
// Source and From select the stored value.  Owner can name the class that
// declares the field when the model does not provide Class.Fields metadata.
type FieldAssignment struct {
	ID         string   `json:"id" yaml:"id"`
	Object     string   `json:"object,omitempty" yaml:"object,omitempty"`
	Receiver   string   `json:"receiver,omitempty" yaml:"receiver,omitempty"`
	Target     string   `json:"target,omitempty" yaml:"target,omitempty"`
	To         string   `json:"to,omitempty" yaml:"to,omitempty"`
	Class      string   `json:"class,omitempty" yaml:"class,omitempty"`
	Field      string   `json:"field" yaml:"field"`
	Name       string   `json:"name,omitempty" yaml:"name,omitempty"`
	Owner      string   `json:"owner,omitempty" yaml:"owner,omitempty"`
	Value      string   `json:"value,omitempty" yaml:"value,omitempty"`
	Source     string   `json:"source,omitempty" yaml:"source,omitempty"`
	From       string   `json:"from,omitempty" yaml:"from,omitempty"`
	Path       []string `json:"path,omitempty" yaml:"path,omitempty"`
	PathString string   `json:"path_string,omitempty" yaml:"path_string,omitempty"`
	Site       string   `json:"site,omitempty" yaml:"site,omitempty"`
}

// VirtualCall is a call site.  Receiver accepts a value ID, an allocation ID,
// a class name, or an expression such as "obj.field".  Object plus Field is
// the structured spelling of the same expression.  StaticType is the declared
// receiver type at the call site.
type VirtualCall struct {
	ID         string   `json:"id" yaml:"id"`
	Receiver   string   `json:"receiver,omitempty" yaml:"receiver,omitempty"`
	Value      string   `json:"value,omitempty" yaml:"value,omitempty"`
	Object     string   `json:"object,omitempty" yaml:"object,omitempty"`
	Field      string   `json:"field,omitempty" yaml:"field,omitempty"`
	StaticType string   `json:"static_type,omitempty" yaml:"static_type,omitempty"`
	Type       string   `json:"type,omitempty" yaml:"type,omitempty"`
	Method     string   `json:"method" yaml:"method"`
	Name       string   `json:"name,omitempty" yaml:"name,omitempty"`
	Signature  string   `json:"signature,omitempty" yaml:"signature,omitempty"`
	Path       []string `json:"path,omitempty" yaml:"path,omitempty"`
	PathString string   `json:"path_string,omitempty" yaml:"path_string,omitempty"`
	Site       string   `json:"site,omitempty" yaml:"site,omitempty"`
}

// Model is the complete finite input to the analysis.
type Model struct {
	Classes          []Class           `json:"classes" yaml:"classes"`
	Allocations      []Allocation      `json:"allocations,omitempty" yaml:"allocations,omitempty"`
	Upcasts          []Upcast          `json:"upcasts,omitempty" yaml:"upcasts,omitempty"`
	FieldAssignments []FieldAssignment `json:"field_assignments,omitempty" yaml:"field_assignments,omitempty"`
	Calls            []VirtualCall     `json:"calls,omitempty" yaml:"calls,omitempty"`
}

// Program and Input are aliases kept for embedding applications.
type Program = Model
type Input = Model

// Step is one edge of an inheritance path.  Index is the position of the
// direct base edge in its parent class, which distinguishes repeated direct
// bases even when their class names are equal.
type Step struct {
	Class      string `json:"class" yaml:"class"`
	Name       string `json:"name,omitempty" yaml:"name,omitempty"`
	Virtual    bool   `json:"virtual,omitempty" yaml:"virtual,omitempty"`
	Index      int    `json:"index,omitempty" yaml:"index,omitempty"`
	Occurrence int    `json:"occurrence,omitempty" yaml:"occurrence,omitempty"`
	Repeated   bool   `json:"repeated,omitempty" yaml:"repeated,omitempty"`
}

// Path is an inheritance path without the most-derived root class.  The
// receiver root is stored separately on refs and provenance records.
type Path []Step

// String renders the class names in a path.
func (p Path) String() string {
	if len(p) == 0 {
		return ""
	}
	out := ""
	for i, step := range p {
		if i != 0 {
			out += "::"
		}
		out += pathStepName(step)
	}
	return out
}

// Classes returns the class names in the path, excluding the root.
func (p Path) Classes() []string {
	if len(p) == 0 {
		return nil
	}
	out := make([]string, len(p))
	for i, step := range p {
		out[i] = step.ClassName()
	}
	return out
}

// Clone returns an independent copy.
func (p Path) Clone() Path {
	if len(p) == 0 {
		return nil
	}
	return append(Path(nil), p...)
}

// ClassName returns the resolved class name of a step.
func (s Step) ClassName() string {
	if s.Class != "" {
		return s.Class
	}
	return s.Name
}

func pathStepName(s Step) string {
	name := s.ClassName()
	if s.Repeated {
		return fmt.Sprintf("%s[%d]", name, s.Occurrence)
	}
	return name
}

// Subobject is one distinct subobject in a materialized complete object.
type Subobject struct {
	Class      string `json:"class" yaml:"class"`
	Identity   string `json:"identity" yaml:"identity"`
	Path       Path   `json:"path,omitempty" yaml:"path,omitempty"`
	PathString string `json:"path_string" yaml:"path_string"`
	Virtual    bool   `json:"virtual,omitempty" yaml:"virtual,omitempty"`
}

// ObjectLayout is the finite materialization of one dynamic class.
type ObjectLayout struct {
	DynamicType string      `json:"dynamic_type" yaml:"dynamic_type"`
	Subobjects  []Subobject `json:"subobjects" yaml:"subobjects"`
}

// Target identifies a concrete member function.
type Target struct {
	Class      string `json:"class" yaml:"class"`
	Method     string `json:"method" yaml:"method"`
	Signature  string `json:"signature,omitempty" yaml:"signature,omitempty"`
	NonVirtual bool   `json:"non_virtual,omitempty" yaml:"non_virtual,omitempty"`
}

// Key returns the stable identity used for target-set comparison.
func (t Target) Key() string {
	return t.Class + "::" + methodKey(t.Method, t.Signature)
}

// String implements fmt.Stringer.
func (t Target) String() string { return t.Key() }

// TraceStep records how an object value reached a call site.
type TraceStep struct {
	Kind  string `json:"kind" yaml:"kind"`
	ID    string `json:"id,omitempty" yaml:"id,omitempty"`
	Site  string `json:"site,omitempty" yaml:"site,omitempty"`
	Field string `json:"field,omitempty" yaml:"field,omitempty"`
	Class string `json:"class,omitempty" yaml:"class,omitempty"`
}

// Provenance explains why one target is reachable.  Allocation is the
// originating allocation site; ReceiverPath is the subobject path from that
// allocation to the call receiver.  Trace additionally records upcasts and
// field stores that participated in the flow.
type Provenance struct {
	Target         Target      `json:"target" yaml:"target"`
	Allocation     string      `json:"allocation" yaml:"allocation"`
	AllocationID   string      `json:"allocation_id,omitempty" yaml:"allocation_id,omitempty"`
	AllocationSite string      `json:"allocation_site,omitempty" yaml:"allocation_site,omitempty"`
	DynamicType    string      `json:"dynamic_type" yaml:"dynamic_type"`
	StaticType     string      `json:"static_type" yaml:"static_type"`
	ReceiverPath   Path        `json:"receiver_path,omitempty" yaml:"receiver_path,omitempty"`
	Path           []string    `json:"path" yaml:"path"`
	SourcePath     []string    `json:"source_path,omitempty" yaml:"source_path,omitempty"`
	Field          string      `json:"field,omitempty" yaml:"field,omitempty"`
	Trace          []TraceStep `json:"trace,omitempty" yaml:"trace,omitempty"`
}

// Ambiguity is a reported non-unique resolution.  Kind is "virtual_slot",
// "call_lookup", "conversion" or "field_lookup".
type Ambiguity struct {
	Kind        string   `json:"kind" yaml:"kind"`
	CallID      string   `json:"call_id,omitempty" yaml:"call_id,omitempty"`
	DynamicType string   `json:"dynamic_type,omitempty" yaml:"dynamic_type,omitempty"`
	StaticType  string   `json:"static_type,omitempty" yaml:"static_type,omitempty"`
	Method      string   `json:"method,omitempty" yaml:"method,omitempty"`
	Field       string   `json:"field,omitempty" yaml:"field,omitempty"`
	Slot        string   `json:"slot,omitempty" yaml:"slot,omitempty"`
	Path        Path     `json:"path,omitempty" yaml:"path,omitempty"`
	Overriders  []Target `json:"overriders,omitempty" yaml:"overriders,omitempty"`
	Targets     []Target `json:"targets,omitempty" yaml:"targets,omitempty"`
	Candidates  []Target `json:"candidates,omitempty" yaml:"candidates,omitempty"`
	Reason      string   `json:"reason" yaml:"reason"`
}

// CallResult is the analysis result for one call site.
type CallResult struct {
	ID            string       `json:"id" yaml:"id"`
	Site          string       `json:"site,omitempty" yaml:"site,omitempty"`
	Method        string       `json:"method" yaml:"method"`
	StaticType    string       `json:"static_type,omitempty" yaml:"static_type,omitempty"`
	Targets       []Target     `json:"targets" yaml:"targets"`
	Candidates    []Target     `json:"candidates,omitempty" yaml:"candidates,omitempty"`
	Provenance    []Provenance `json:"provenance,omitempty" yaml:"provenance,omitempty"`
	Ambiguous     bool         `json:"ambiguous,omitempty" yaml:"ambiguous,omitempty"`
	Ambiguities   []Ambiguity  `json:"ambiguities,omitempty" yaml:"ambiguities,omitempty"`
	NonVirtual    bool         `json:"non_virtual,omitempty" yaml:"non_virtual,omitempty"`
	ReceiverCount int          `json:"receiver_count" yaml:"receiver_count"`
	Validation    Validation   `json:"validation" yaml:"validation"`
	Error         string       `json:"error,omitempty" yaml:"error,omitempty"`
}

// Validation is the cross-check produced by the finite object execution
// model.  Missing is the soundness-critical field: a non-empty Missing means a
// concrete receiver could reach a target absent from the candidate set.
type Validation struct {
	OK            bool     `json:"ok" yaml:"ok"`
	Expected      []Target `json:"expected,omitempty" yaml:"expected,omitempty"`
	Missing       []Target `json:"missing,omitempty" yaml:"missing,omitempty"`
	Spurious      []Target `json:"spurious,omitempty" yaml:"spurious,omitempty"`
	ReceiverCount int      `json:"receiver_count,omitempty" yaml:"receiver_count,omitempty"`
	Messages      []string `json:"messages,omitempty" yaml:"messages,omitempty"`
}

// Result is the complete analysis output.
type Result struct {
	Calls       []CallResult            `json:"calls" yaml:"calls"`
	ByCall      map[string]CallResult   `json:"by_call,omitempty" yaml:"by_call,omitempty"`
	Targets     map[string][]Target     `json:"targets,omitempty" yaml:"targets,omitempty"`
	Candidates  map[string][]Target     `json:"candidates,omitempty" yaml:"candidates,omitempty"`
	Ambiguities []Ambiguity             `json:"ambiguities,omitempty" yaml:"ambiguities,omitempty"`
	Layouts     map[string]ObjectLayout `json:"layouts,omitempty" yaml:"layouts,omitempty"`
	Validation  Validation              `json:"validation" yaml:"validation"`
	Validated   bool                    `json:"validated" yaml:"validated"`
	Diagnostics []string                `json:"diagnostics,omitempty" yaml:"diagnostics,omitempty"`
}

// TargetsForCall is a convenience accessor.
func (r *Result) TargetsForCall(id string) []Target {
	if r == nil {
		return nil
	}
	return append([]Target(nil), r.Targets[id]...)
}

// AnalysisError reports a strict-analysis failure.
type AnalysisError struct {
	Kind  string
	Cause error
	Items []string
}

func (e *AnalysisError) Error() string {
	if e == nil {
		return "<nil>"
	}
	if len(e.Items) == 0 {
		return e.Kind
	}
	return fmt.Sprintf("%s: %v", e.Kind, e.Items)
}

func (e *AnalysisError) Unwrap() error { return e.Cause }

// Sentinel errors.
var (
	ErrInvalidModel         = errors.New("typeset: invalid model")
	ErrInheritanceCycle     = errors.New("typeset: inheritance cycle")
	ErrUnknownClass         = errors.New("typeset: unknown class")
	ErrDuplicateClass       = errors.New("typeset: duplicate class")
	ErrDuplicateID          = errors.New("typeset: duplicate id")
	ErrUnknownMethod        = errors.New("typeset: unknown method")
	ErrInvalidConversion    = errors.New("typeset: invalid upcast")
	ErrAmbiguousVirtualSlot = errors.New("typeset: ambiguous shared virtual slot")
	ErrValidationFailed     = errors.New("typeset: finite-model validation failed")
)

// Compatibility aliases for embedding code.
var (
	ErrCyclicInheritance        = ErrInheritanceCycle
	ErrAmbiguousVirtualBase     = ErrAmbiguousVirtualSlot
	ErrAmbiguousVirtualBaseSlot = ErrAmbiguousVirtualSlot
	ErrAmbiguousSlot            = ErrAmbiguousVirtualSlot
)

// CycleError contains one concrete inheritance cycle.
type CycleError struct {
	Cycle []string
}

func (e *CycleError) Error() string {
	if e == nil {
		return ErrInheritanceCycle.Error()
	}
	return fmt.Sprintf("%s: %s", ErrInheritanceCycle, joinArrow(e.Cycle))
}

func (e *CycleError) Unwrap() error { return ErrInheritanceCycle }

// AmbiguityError summarizes all ambiguities found by a strict analysis.
type AmbiguityError struct {
	Items []Ambiguity
}

func (e *AmbiguityError) Error() string {
	if e == nil || len(e.Items) == 0 {
		return ErrAmbiguousVirtualSlot.Error()
	}
	return fmt.Sprintf("%s: %s", ErrAmbiguousVirtualSlot, e.Items[0].Reason)
}

func (e *AmbiguityError) Unwrap() error { return ErrAmbiguousVirtualSlot }

func joinArrow(items []string) string {
	out := ""
	for i, item := range items {
		if i != 0 {
			out += " -> "
		}
		out += item
	}
	return out
}

func methodKey(name, signature string) string {
	if signature != "" {
		return signature
	}
	return name
}

func (m Method) key() string { return methodKey(m.Name, m.Signature) }

func (m Method) virtual() bool {
	if m.NonVirtual || m.Static {
		return false
	}
	switch m.Kind {
	case "nonvirtual", "non-virtual", "static", "non_virtual":
		return false
	}
	// Virtual is intentionally not required.  This package analyzes virtual
	// calls, and C++ members with the same signature as a virtual base member
	// are implicitly virtual.  Keeping the default virtual makes the model
	// usable even when only method names are supplied.
	return true
}
