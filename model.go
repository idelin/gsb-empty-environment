package netsec

import (
	"fmt"
	"sync"
)

// Model is a frozen model instance. All tensor reads come from the file
// handles captured by Freeze. Once a read fails verification, the whole
// instance is invalidated and every later tensor operation fails.
type Model struct {
	mu sync.Mutex

	root        DirHandle
	files       map[string]*frozenFile
	tensors     map[string]*tensorEntry
	graphDigest Digest
	manifest    WeightManifest
	invalid     error
	closed      bool
}

// Close releases the frozen file and directory handles. It is safe to call
// more than once.
func (m *Model) Close() error {
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.closed {
		return nil
	}
	m.closed = true
	return m.closeHandlesLocked()
}

func (m *Model) closeHandlesLocked() error {
	var first error
	for _, file := range m.files {
		if file != nil && file.handle != nil {
			if err := file.handle.Close(); err != nil && first == nil {
				first = err
			}
		}
	}
	m.files = nil
	if m.root != nil {
		if err := m.root.Close(); err != nil && first == nil {
			first = err
		}
		m.root = nil
	}
	return first
}

func (m *Model) invalidateLocked(cause error) error {
	if m.invalid == nil {
		if cause == nil {
			cause = fmt.Errorf("unspecified verification failure")
		}
		m.invalid = fmt.Errorf("%w: %w", ErrModelInvalid, cause)
	}
	_ = m.closeHandlesLocked()
	return m.invalid
}

func (m *Model) stateErrorLocked() error {
	if m.invalid != nil {
		return m.invalid
	}
	if m.closed {
		return ErrModelClosed
	}
	return nil
}

// GraphDigest returns the graph digest bound into the frozen manifest.
func (m *Model) GraphDigest() Digest {
	m.mu.Lock()
	defer m.mu.Unlock()
	return m.graphDigest
}

// Manifest returns a deep copy of the frozen weight manifest, including the
// graph digest, file identities, and tensor ranges.
func (m *Model) Manifest() WeightManifest {
	m.mu.Lock()
	defer m.mu.Unlock()
	return cloneManifest(m.manifest)
}

// Invalid returns the error that invalidated the model, or nil if the model
// is still valid. A closed model is not reported as invalid.
func (m *Model) Invalid() error {
	m.mu.Lock()
	defer m.mu.Unlock()
	return m.invalid
}

// Tensor returns a copy of the tensor bytes. It verifies every frozen file's
// identity and the requested range before returning any bytes. A failed check
// invalidates the entire model.
func (m *Model) Tensor(tensorID string) ([]byte, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	if err := m.stateErrorLocked(); err != nil {
		return nil, err
	}
	entry, ok := m.tensors[tensorID]
	if !ok {
		return nil, fmt.Errorf("%w: %q", ErrUnknownTensor, tensorID)
	}
	if err := m.verifyFilesLocked(); err != nil {
		return nil, m.invalidateLocked(err)
	}
	if err := verifyFrozenFile(entry.file); err != nil {
		return nil, m.invalidateLocked(err)
	}
	data, err := readRange(entry.file.handle, entry.Offset, entry.Length)
	if err != nil {
		return nil, m.invalidateLocked(fmt.Errorf("tensor %q: %w", tensorID, err))
	}
	if digest := SumDigest(data); digest != entry.SHA256 {
		return nil, m.invalidateLocked(fmt.Errorf(
			"%w: tensor %q: got %s, want %s",
			ErrDigestMismatch, tensorID, digest, entry.SHA256,
		))
	}
	if err := verifyFrozenFile(entry.file); err != nil {
		return nil, m.invalidateLocked(err)
	}
	return data, nil
}

// ReadTensor reads a tensor and invokes callback with a private copy of its
// bytes. The callback is invoked only after all verification succeeds and
// after the model lock is released.
func (m *Model) ReadTensor(tensorID string, callback func([]byte) error) error {
	if callback == nil {
		return fmt.Errorf("%w: nil tensor callback", ErrInvalidInitializer)
	}
	data, err := m.Tensor(tensorID)
	if err != nil {
		return err
	}
	return callback(data)
}

// Verify re-checks every frozen file identity and every tensor range digest.
// Any failure invalidates the whole model.
func (m *Model) Verify() error {
	m.mu.Lock()
	defer m.mu.Unlock()
	if err := m.stateErrorLocked(); err != nil {
		return err
	}
	if err := m.verifyFilesLocked(); err != nil {
		return m.invalidateLocked(err)
	}
	for id, entry := range m.tensors {
		digest, err := hashRange(entry.file.handle, entry.Offset, entry.Length)
		if err != nil {
			return m.invalidateLocked(fmt.Errorf("tensor %q: %w", id, err))
		}
		if digest != entry.SHA256 {
			return m.invalidateLocked(fmt.Errorf(
				"%w: tensor %q: got %s, want %s",
				ErrDigestMismatch, id, digest, entry.SHA256,
			))
		}
		if err := verifyFrozenFile(entry.file); err != nil {
			return m.invalidateLocked(err)
		}
	}
	return nil
}

// VerifyManifest compares expected with the manifest generated by Freeze and
// then verifies all frozen data. A mismatch invalidates the whole model.
func (m *Model) VerifyManifest(expected WeightManifest) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	if err := m.stateErrorLocked(); err != nil {
		return err
	}
	if !manifestsEqual(expected, m.manifest) {
		return m.invalidateLocked(ErrManifestMismatch)
	}
	if err := m.verifyFilesLocked(); err != nil {
		return m.invalidateLocked(err)
	}
	for id, entry := range m.tensors {
		digest, err := hashRange(entry.file.handle, entry.Offset, entry.Length)
		if err != nil {
			return m.invalidateLocked(fmt.Errorf("tensor %q: %w", id, err))
		}
		if digest != entry.SHA256 {
			return m.invalidateLocked(fmt.Errorf(
				"%w: tensor %q: got %s, want %s",
				ErrDigestMismatch, id, digest, entry.SHA256,
			))
		}
		if err := verifyFrozenFile(entry.file); err != nil {
			return m.invalidateLocked(err)
		}
	}
	return nil
}

func (m *Model) verifyFilesLocked() error {
	for _, file := range m.files {
		if err := verifyFrozenFile(file); err != nil {
			return err
		}
	}
	return nil
}

func readRange(file FileHandle, offset, length int64) ([]byte, error) {
	maxInt := int64(^uint(0) >> 1)
	if length < 0 || length > maxInt {
		return nil, fmt.Errorf("%w: tensor length %d cannot be represented", ErrInvalidInitializer, length)
	}
	buffer := make([]byte, int(length))
	if err := readAtExact(file, buffer, offset); err != nil {
		return nil, err
	}
	return buffer, nil
}
