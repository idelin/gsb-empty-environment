package paxos

import (
	"fmt"
	"sort"
)

// Envelope is a message in flight between two nodes.
type Envelope struct {
	ID   int
	From int
	To   int
	Msg  Message
}

// Sim drives a fixed cluster of nodes with an explicit, fully controlled
// message queue: every delivery, drop, duplication, crash and restart is
// an explicit event stamped with an integer tick.
type Sim struct {
	Nodes   []*Node
	Checker *Checker
	Tick    int

	pending   []Envelope
	nextID    int
	Trace     []string
	sentCount []int
}

// NewSim builds a cluster of n nodes. If stores is nil, fresh in-memory
// stores are used.
func NewSim(n int, stores []Store) *Sim {
	s := &Sim{Checker: NewChecker(n/2 + 1)}
	s.sentCount = make([]int, n)
	for i := 0; i < n; i++ {
		var st Store
		if stores != nil {
			st = stores[i]
		} else {
			st = NewMemStore()
		}
		s.Nodes = append(s.Nodes, NewNode(i, n, st))
	}
	return s
}

// NewSimMem builds a cluster backed by in-memory stores and returns them
// so tests can toggle persistence failures.
func NewSimMem(n int) (*Sim, []*MemStore) {
	stores := make([]Store, n)
	mem := make([]*MemStore, n)
	for i := range stores {
		mem[i] = NewMemStore()
		stores[i] = mem[i]
	}
	return NewSim(n, stores), mem
}

func (s *Sim) tracef(format string, args ...interface{}) {
	s.Trace = append(s.Trace, fmt.Sprintf("tick=%-4d %s", s.Tick, fmt.Sprintf(format, args...)))
}

func (s *Sim) send(from int, outs []Outbound) {
	for _, o := range outs {
		targets := []int{o.To}
		if o.To < 0 {
			targets = targets[:0]
			for i := range s.Nodes {
				targets = append(targets, i)
			}
		}
		for _, to := range targets {
			env := Envelope{ID: s.nextID, From: from, To: to, Msg: o.Msg}
			s.nextID++
			s.pending = append(s.pending, env)
			s.sentCount[from]++
			s.tracef("send    #%-3d %d->%d %s", env.ID, from, to, env.Msg)
			// An Accepted message is only sent after the acceptor durably
			// persisted the accept, so it is valid chosen-evidence already.
			if env.Msg.Kind == MsgAccepted {
				s.Checker.Observe(env.Msg, from)
			}
		}
	}
}

// CountSent returns how many messages a node has emitted.
func (s *Sim) CountSent(from int) int { return s.sentCount[from] }

// Pending returns a snapshot of the undelivered messages.
func (s *Sim) Pending() []Envelope { return append([]Envelope(nil), s.pending...) }

func (s *Sim) find(id int) int {
	for i, e := range s.pending {
		if e.ID == id {
			return i
		}
	}
	return -1
}

// Deliver delivers one pending message by ID. Delivering to a down node
// loses the message.
func (s *Sim) Deliver(id int) bool {
	i := s.find(id)
	if i < 0 {
		return false
	}
	env := s.pending[i]
	s.pending = append(s.pending[:i], s.pending[i+1:]...)
	node := s.Nodes[env.To]
	if !node.Up {
		s.tracef("lost    #%-3d %d->%d %s (node down)", env.ID, env.From, env.To, env.Msg)
		return true
	}
	s.tracef("deliver #%-3d %d->%d %s", env.ID, env.From, env.To, env.Msg)
	s.send(env.To, node.Handle(env.From, env.Msg))
	return true
}

// Drop discards one pending message by ID.
func (s *Sim) Drop(id int) bool {
	i := s.find(id)
	if i < 0 {
		return false
	}
	env := s.pending[i]
	s.pending = append(s.pending[:i], s.pending[i+1:]...)
	s.tracef("drop    #%-3d %d->%d %s", env.ID, env.From, env.To, env.Msg)
	return true
}

// DropAll discards every pending message.
func (s *Sim) DropAll() {
	for len(s.pending) > 0 {
		s.Drop(s.pending[0].ID)
	}
}

// Dup duplicates a pending message (new ID) and returns the copy's ID.
func (s *Sim) Dup(id int) (int, bool) {
	i := s.find(id)
	if i < 0 {
		return 0, false
	}
	env := s.pending[i]
	env.ID = s.nextID
	s.nextID++
	s.pending = append(s.pending, env)
	s.tracef("dup     #%-3d %d->%d %s", env.ID, env.From, env.To, env.Msg)
	return env.ID, true
}

// Inject enqueues a hand-crafted message (used to test stale ballots).
func (s *Sim) Inject(from, to int, m Message) int {
	env := Envelope{ID: s.nextID, From: from, To: to, Msg: m}
	s.nextID++
	s.pending = append(s.pending, env)
	s.tracef("inject  #%-3d %d->%d %s", env.ID, from, to, m)
	return env.ID
}

// DeliverAll delivers every pending message in FIFO order until the queue
// drains (fair delivery).
func (s *Sim) DeliverAll() {
	for len(s.pending) > 0 {
		s.Deliver(s.pending[0].ID)
	}
}

// DeliverAllReverse delivers LIFO, exercising reordering tolerance.
func (s *Sim) DeliverAllReverse() {
	for len(s.pending) > 0 {
		s.Deliver(s.pending[len(s.pending)-1].ID)
	}
}

// DeliverWhere delivers, in ID order, all currently pending messages that
// match pred. Messages generated by those deliveries are not included.
func (s *Sim) DeliverWhere(pred func(Envelope) bool) int {
	var ids []int
	for _, e := range s.pending {
		if pred(e) {
			ids = append(ids, e.ID)
		}
	}
	for _, id := range ids {
		s.Deliver(id)
	}
	return len(ids)
}

// StartLeader makes node i begin phase 1 with a fresh ballot.
func (s *Sim) StartLeader(i int) { s.send(i, s.Nodes[i].StartLeader()) }

// Propose submits a client value to node i.
func (s *Sim) Propose(i int, v Value) { s.send(i, s.Nodes[i].Propose(v)) }

// Crash halts node i, losing its volatile state.
func (s *Sim) Crash(i int) {
	s.Nodes[i].Crash()
	s.tracef("crash   node %d", i)
}

// Restart brings node i back, reloading durable state from its store.
func (s *Sim) Restart(i int) {
	s.Nodes[i].Restart()
	s.tracef("restart node %d", i)
}

// ChosenEvidence proves that a slot's value is chosen: a majority of
// distinct acceptors accepted the same (ballot, value).
type ChosenEvidence struct {
	Value     Value
	Ballot    Ballot
	Acceptors []int
}

// Checker independently verifies Paxos safety from the stream of Accepted
// messages, without trusting any node's own bookkeeping.
type Checker struct {
	majority int
	accepts  map[int]map[Ballot]map[Value]map[int]bool // slot -> ballot -> value -> acceptors
}

func NewChecker(majority int) *Checker {
	return &Checker{majority: majority, accepts: map[int]map[Ballot]map[Value]map[int]bool{}}
}

// Observe records one acceptor's durable accept.
func (c *Checker) Observe(m Message, from int) {
	if m.Kind != MsgAccepted {
		return
	}
	byBallot, ok := c.accepts[m.Slot]
	if !ok {
		byBallot = map[Ballot]map[Value]map[int]bool{}
		c.accepts[m.Slot] = byBallot
	}
	byValue, ok := byBallot[m.Ballot]
	if !ok {
		byValue = map[Value]map[int]bool{}
		byBallot[m.Ballot] = byValue
	}
	set, ok := byValue[m.Value]
	if !ok {
		set = map[int]bool{}
		byValue[m.Value] = set
	}
	set[from] = true
}

// Chosen returns, per slot, the chosen value with its evidence.
func (c *Checker) Chosen() map[int]ChosenEvidence {
	out := map[int]ChosenEvidence{}
	for slot, byBallot := range c.accepts {
		for ballot, byValue := range byBallot {
			for v, set := range byValue {
				if len(set) >= c.majority {
					ev := ChosenEvidence{Value: v, Ballot: ballot}
					for a := range set {
						ev.Acceptors = append(ev.Acceptors, a)
					}
					sort.Ints(ev.Acceptors)
					if cur, ok := out[slot]; !ok || ballot.Compare(cur.Ballot) > 0 {
						out[slot] = ev
					}
				}
			}
		}
	}
	return out
}

// Check verifies the two safety properties:
//  1. no slot is chosen with two different values;
//  2. every value any node applied is in fact chosen.
func (c *Checker) Check(nodes []*Node) error {
	for slot, byBallot := range c.accepts {
		chosenValues := map[Value]bool{}
		for _, byValue := range byBallot {
			for v, set := range byValue {
				if len(set) >= c.majority {
					chosenValues[v] = true
				}
			}
		}
		if len(chosenValues) > 1 {
			return fmt.Errorf("SAFETY VIOLATION: slot %d chosen with %d different values", slot, len(chosenValues))
		}
	}
	chosen := c.Chosen()
	for _, nd := range nodes {
		for slot, v := range nd.Applied() {
			ev, ok := chosen[slot]
			if !ok {
				return fmt.Errorf("SAFETY VIOLATION: node %d applied unchosen value %s at slot %d", nd.ID, formatValue(v), slot)
			}
			if ev.Value != v {
				return fmt.Errorf("SAFETY VIOLATION: node %d applied %s at slot %d but chosen value is %s",
					nd.ID, formatValue(v), slot, formatValue(ev.Value))
			}
		}
	}
	return nil
}
