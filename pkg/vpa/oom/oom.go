// Package oom implements the memory OOM bump-up behaviour of the VPA
// recommender: every observed OOM event produces a virtual "bumped" memory
// sample that is guaranteed to exceed the container's limit at the time of the
// crash, and recent bumps act as a hard floor on memory recommendations until
// they age out of the sliding window.
package oom

import (
	"sort"
	"time"
)

// Default tuning constants, matching the upstream VPA recommender defaults.
const (
	// DefaultBumpUpRatio is the multiplicative headroom applied to the OOM
	// memory limit.
	DefaultBumpUpRatio = 1.2
	// DefaultMinBumpUp is the additive headroom applied to the OOM memory
	// limit.
	DefaultMinBumpUp int64 = 100 * 1024 * 1024
	// DefaultWindow is how long an OOM event keeps influencing
	// recommendations.
	DefaultWindow = 7 * 24 * time.Hour
)

// Event records one container OOM: the memory limit configured when the
// container was killed and when it happened.
type Event struct {
	// Memory is the container memory limit (bytes) configured when the OOM
	// occurred.
	Memory int64
	At     time.Time
}

// Bumper turns raw OOM events into bumped memory samples and keeps the events
// inside a sliding time window.
type Bumper struct {
	bumpUpRatio float64
	minBumpUp   int64
	window      time.Duration
	events      []Event
}

// NewBumper builds a Bumper. Non-positive arguments fall back to the upstream
// VPA defaults.
func NewBumper(bumpUpRatio float64, minBumpUp int64, window time.Duration) *Bumper {
	if bumpUpRatio <= 1 {
		bumpUpRatio = DefaultBumpUpRatio
	}
	if minBumpUp <= 0 {
		minBumpUp = DefaultMinBumpUp
	}
	if window <= 0 {
		window = DefaultWindow
	}
	return &Bumper{
		bumpUpRatio: bumpUpRatio,
		minBumpUp:   minBumpUp,
		window:      window,
	}
}

// BumpMemory computes the virtual memory sample for an OOM that happened at
// oomMemory: max(oomMemory*bumpUpRatio, oomMemory+minBumpUp).
func (b *Bumper) BumpMemory(oomMemory int64) int64 {
	if oomMemory <= 0 {
		return b.minBumpUp
	}
	ratioBumped := int64(float64(oomMemory)*b.bumpUpRatio + 0.5)
	additiveBumped := oomMemory + b.minBumpUp
	if ratioBumped > additiveBumped {
		return ratioBumped
	}
	return additiveBumped
}

// Record stores an OOM event and returns the corresponding bumped sample.
// Events are expected to arrive in chronological order.
func (b *Bumper) Record(event Event) int64 {
	b.events = append(b.events, event)
	return b.BumpMemory(event.Memory)
}

// prune drops events older than the window relative to now.
func (b *Bumper) prune(now time.Time) {
	cutoff := now.Add(-b.window)
	kept := b.events[:0]
	for _, event := range b.events {
		if event.At.After(cutoff) {
			kept = append(kept, event)
		}
	}
	b.events = kept
}

// ActiveEvents returns the OOM events still inside the window at time now.
func (b *Bumper) ActiveEvents(now time.Time) []Event {
	b.prune(now)
	events := make([]Event, len(b.events))
	copy(events, b.events)
	return events
}

// BumpFloor returns the largest bumped sample generated by an unexpired OOM
// event at time now. It is the hard lower bound for memory recommendations.
// The second return value is false when no OOM event is currently active.
func (b *Bumper) BumpFloor(now time.Time) (int64, bool) {
	b.prune(now)
	if len(b.events) == 0 {
		return 0, false
	}
	floor := int64(0)
	for _, event := range b.events {
		if bumped := b.BumpMemory(event.Memory); bumped > floor {
			floor = bumped
		}
	}
	return floor, true
}

// Window returns the configured sliding window.
func (b *Bumper) Window() time.Duration { return b.window }

// LatestEventAt returns the timestamp of the most recent stored OOM event, or
// the zero time when none exists.
func (b *Bumper) LatestEventAt() time.Time {
	if len(b.events) == 0 {
		return time.Time{}
	}
	events := append([]Event(nil), b.events...)
	sort.Slice(events, func(i, j int) bool { return events[i].At.Before(events[j].At) })
	return events[len(events)-1].At
}
