package netsec

import (
	"bytes"
	"crypto/rand"
	"encoding/base64"
	"fmt"
	"mime"
	"strings"
)

const defaultAttachmentType = "application/octet-stream"

func generateBoundary() (string, error) {
	random := make([]byte, 24)
	if _, err := rand.Read(random); err != nil {
		return "", fmt.Errorf("netsec: generate MIME boundary: %w", err)
	}
	// The prefix is outside the standard base64 alphabet, so boundary text
	// cannot be produced accidentally by the base64 attachment encoder.
	return "=_netsec_" + base64.RawURLEncoding.EncodeToString(random), nil
}

// GenerateBoundary returns a cryptographically random RFC 2046 boundary. It is
// exposed for integration tests and server-side tooling; Message always
// generates and owns its own boundary and never accepts a caller-supplied one.
func GenerateBoundary() (string, error) {
	return generateBoundary()
}

func normalizeAttachmentType(value string) (string, error) {
	if value == "" {
		return defaultAttachmentType, nil
	}
	if err := validateText(value, "attachment content type"); err != nil {
		return "", err
	}
	for i := 0; i < len(value); i++ {
		if value[i] >= 0x80 {
			return "", fmt.Errorf("%w: media type must be ASCII", ErrEncodedInput)
		}
	}
	parsed, params, err := mime.ParseMediaType(value)
	if err != nil {
		return "", fmt.Errorf("%w: %v", ErrInvalidMIME, err)
	}
	if len(params) != 0 {
		return "", fmt.Errorf("%w: parameters are generated by the server", ErrInvalidMIME)
	}
	if strings.HasPrefix(parsed, "multipart/") {
		return "", fmt.Errorf("%w: nested multipart is not allowed", ErrInvalidMIME)
	}
	if !validMediaType(parsed) {
		return "", fmt.Errorf("%w: malformed media type", ErrInvalidMIME)
	}
	return strings.ToLower(parsed), nil
}

func validMediaType(value string) bool {
	slash := strings.IndexByte(value, '/')
	if slash <= 0 || slash == len(value)-1 || strings.Contains(value[slash+1:], "/") {
		return false
	}
	for i := 0; i < len(value); i++ {
		if value[i] == '/' {
			continue
		}
		if !validTokenByte(value[i]) {
			return false
		}
	}
	return true
}

func validTokenByte(b byte) bool {
	if (b >= 'a' && b <= 'z') || (b >= 'A' && b <= 'Z') || (b >= '0' && b <= '9') {
		return true
	}
	switch b {
	case '!', '#', '$', '&', '-', '^', '_', '.', '+', '\'', '*', '`', '|', '~':
		return true
	default:
		return false
	}
}

func dispositionTokens(filename string) ([]string, error) {
	if err := validateText(filename, "attachment filename"); err != nil {
		return nil, err
	}
	fallback := asciiFallback(filename)
	extended := percentEncodeRFC2231(filename)

	tokens := []string{"attachment;", `filename="` + escapeQuoted(fallback) + `";`}
	if len(extended) <= 50 {
		tokens = append(tokens, "filename*=UTF-8''"+extended)
		return tokens, nil
	}

	chunks := splitPercentEncoding(extended, 48)
	for i, chunk := range chunks {
		prefix := fmt.Sprintf("filename*%d*=", i)
		if i == 0 {
			prefix += "UTF-8''"
		}
		token := prefix + chunk
		if i < len(chunks)-1 {
			token += ";"
		}
		tokens = append(tokens, token)
	}
	return tokens, nil
}

func asciiFallback(filename string) string {
	var b strings.Builder
	b.Grow(len(filename))
	for _, r := range filename {
		if r >= 0x20 && r <= 0x7e && r != '"' && r != '\\' {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	value := b.String()
	if value == "" {
		value = "attachment"
	}
	if len(value) > 60 {
		value = value[:60]
	}
	return value
}

func escapeQuoted(value string) string {
	return strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(value)
}

func percentEncodeRFC2231(value string) string {
	var b strings.Builder
	for _, r := range value {
		raw := []byte(string(r))
		if len(raw) == 1 && isAttrChar(raw[0]) {
			b.WriteByte(raw[0])
			continue
		}
		for _, item := range raw {
			fmt.Fprintf(&b, "%%%02X", item)
		}
	}
	return b.String()
}

func isAttrChar(b byte) bool {
	if (b >= 'a' && b <= 'z') || (b >= 'A' && b <= 'Z') || (b >= '0' && b <= '9') {
		return true
	}
	switch b {
	case '!', '#', '$', '&', '+', '-', '.', '^', '_', '`', '|', '~':
		return true
	default:
		return false
	}
}

func splitPercentEncoding(value string, max int) []string {
	var chunks []string
	var current strings.Builder
	for len(value) > 0 {
		tokenSize := 1
		if value[0] == '%' && len(value) >= 3 {
			tokenSize = 3
		}
		token := value[:tokenSize]
		if current.Len() > 0 && current.Len()+tokenSize > max {
			chunks = append(chunks, current.String())
			current.Reset()
		}
		current.WriteString(token)
		value = value[tokenSize:]
	}
	if current.Len() > 0 {
		chunks = append(chunks, current.String())
	}
	return chunks
}

func boundaryCollides(boundary, body string, attachments []Attachment) bool {
	needle := []byte("--" + boundary)
	if bytes.Contains([]byte(body), needle) {
		return true
	}
	for _, attachment := range attachments {
		if bytes.Contains([]byte(base64.StdEncoding.EncodeToString(attachment.Data)), needle) {
			return true
		}
	}
	return false
}
