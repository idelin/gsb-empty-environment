// Package connauthz 为嵌入 Go 服务的长连接授权提供按“代次（generation）”复验的能力。
//
// 背景：机房切换信任根时，TLS 长连接可能在握手时合法、之后其证书却被撤销。
// 仅依赖握手时一次校验的服务，仍会允许该连接继续创建新流。本包把授权拆成两步：
//
//   - 连接建立（TLS 握手）时，记录对端出示的完整证书链（[Connection]）；
//   - 每次创建新流（[AuthorizedMux.OpenStream] 或 [Authorizer.Authorize]）时，
//     用当前最新一代 [Policy] 重新构建并校验证书路径，而不是复用握手时的结论。
//
// 授权生效顺序（轮换与开流并发）：
//
//   - [Policy] 不可变，每代有严格递增的 Generation；[Authorizer.Rotate] 通过
//     原子指针换入新代，换入前的开流请求用旧代、换入后的用新代，单次开流全程
//     只观察同一代策略。
//   - Rotate 返回即表示新代已全局生效（happens-before）；Rotate 拒绝回退代次，
//     因此已观察到第 N 代的调用方不会再观察到第 N-1 代。
//   - 旧流按既有决定结束：授权只发生在“开流”这一时刻；已经打开的流不会被
//     追溯关闭或中断，由流自身的生命周期管理负责。
//
// 撤销的粒度是“证书”而非“公钥/主体”：交叉签名产生的多份证书（同主体、同密钥、
// 不同签发者）互不牵连，撤销一条路径不会误伤另一条可信路径。
