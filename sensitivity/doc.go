// Package sensitivity 为安全统计编译器推导查询计划对单条输入变化的最大影响
// （L1 敏感度）。
//
// 包内所有数值均使用 math/big.Rat 精确表示，避免浮点误差影响上界核验。
// 支持的查询算子（均以 AST 节点描述）：
//
//   - [Source]：基础关系，单条输入变化即该关系中一行的加入或删除。
//   - [BoundedCount]：有界计数，行数超过容量上界时截断。
//   - [TruncatedSum]：截断求和，每个单元先夹取到 [Lower, Upper] 再求和。
//   - [Project]：投影，保留部分列；行级敏感度不变。
//   - [Union]：并集（UNION ALL 语义），两个同模式子计划合并。
//   - [Join]：按已知唯一键连接；放大倍数只能取连接两侧显式给出的
//     重复上界，任一侧缺少上界则敏感度为未知。
//
// 典型用法是先构造 AST，再调用 [Derive] 得到逐节点推导 [Trace]，
// 需要时调用 [Eval] 对具体数据求值，并调用 [Verify] 在小数据集上
// 枚举相邻输入（相差一行的数据集对）核验推导上界是否被突破。
