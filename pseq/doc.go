// 每个 Version 是序列的一个不可变快照：两端添加/删除、拼接、区间剪切
// 都返回新版本，旧版本继续有效。不同操作路径得到相同序列时，其
// 多项式摘要（模 Mod 意义下）与长度必然相同；但摘要相同不代表内容
// 相同（模碰撞、前导零序列等），内容相等须用 EqualContent 判定。
//
// 元素在进入结构前统一规范到 [0, Mod)：负整数先取模。
//
// 节点在版本间结构共享，引用计数管理；Release 释放版本句柄后，
// 不可达节点被准确回收（见 LiveNodes）。
