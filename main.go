package main

import "fmt"

func main() {
	// 场景：三层，坐标尺度大（不栅格化），含孔洞、共边、完全遮挡。
	layers := [][]Rect{
		// 层 0：底板 [0,1e9]² 挖一个孔洞（孔洞与上层重叠）
		NewLayerWithHoles(Rect{0, 0, 1_000_000_000, 1_000_000_000},
			[]Rect{{400_000_000, 400_000_000, 600_000_000, 600_000_000}}),
		// 层 1：两个共边相邻的矩形 + 一个孔洞
		NewLayerWithHoles(Rect{200_000_000, 200_000_000, 500_000_000, 800_000_000},
			[]Rect{{300_000_000, 300_000_000, 350_000_000, 350_000_000}}),
		// 层 2：完全遮住层 1 的一部分，自身带孔洞，孔洞处可透视到层 1
		NewLayerWithHoles(Rect{200_000_000, 200_000_000, 800_000_000, 500_000_000},
			[]Rect{{450_000_000, 450_000_000, 550_000_000, 550_000_000}}),
	}

	fmt.Println("== 图层定义 ==")
	describeLayers(layers)

	areas, visible := VisibleAreas(layers)
	fmt.Println("\n== 各层最终可见面积 ==")
	for i, a := range areas {
		fmt.Printf("  层 %d: 可见面积 %d（可见分块 %d 块: %v）\n", i, a, len(visible[i]), visible[i])
	}

	sum, union, ok := CheckConservation(layers)
	fmt.Println("\n== 面积守恒检查 ==")
	fmt.Printf("  各层可见面积之和 = %d\n  全体并集面积     = %d\n  守恒: %v\n", sum, union, ok)

	lm := NewLayerMap(layers)
	fmt.Println("\n== 任意点最上层查询 ==")
	points := [][2]int64{
		{100_000_000, 100_000_000}, // 仅层 0
		{460_000_000, 460_000_000}, // 层 0 孔 ∩ 层 2 孔，透视到层 1 实体 -> 层 1
		{500_000_000, 500_000_000}, // 三层均透明（孔洞重叠 + 层 1 边界外）-> -1
		{300_000_000, 300_000_000}, // 层 1 的孔洞，但层 2 实体覆盖 -> 层 2
		{250_000_000, 600_000_000}, // 层 1 实体（层 2 未覆盖）-> 层 1
		{700_000_000, 300_000_000}, // 层 2 实体 -> 层 2
		{500_000_000, 700_000_000}, // 层 1/2 均未覆盖 -> 层 0
		{2_000_000_000, 0},         // 所有层之外 -> -1
	}
	for _, p := range points {
		fmt.Printf("  点 (%d, %d) -> 最上层 %d（暴力校验 %d）\n",
			p[0], p[1], lm.TopmostAt(p[0], p[1]), TopmostAt(layers, p[0], p[1]))
	}
}
