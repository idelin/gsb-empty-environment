// Package netsec implements verifier-side validation of an ISO/IEC 18013-5
// (mdoc / mobile driving licence) response.
//
// The package works on already-decoded IssuerSigned and DeviceSigned data and
// never performs CBOR/COSE decoding or cryptographic operations itself.
// Hashing and device-signature verification are supplied by the caller through
// callbacks, which keeps the package free of any third-party dependency.
package netsec

import "time"

// RequestedElement identifies a single data element that the verifier asked
// for in its request, identified by namespace and element identifier.
type RequestedElement struct {
	NameSpace         string
	ElementIdentifier string
}

// IssuerSignedItem is one decoded issuer-signed data element as carried in
// IssuerSigned.nameSpaces. The byte string wrapping (tag 24) and any CBOR
// framing are expected to have already been removed by the caller.
type IssuerSignedItem struct {
	DigestID          uint64
	Random            []byte
	ElementIdentifier string
	ElementValue      any
}

// IssuerNameSpaces maps namespace names to the data elements returned in
// that namespace.
type IssuerNameSpaces map[string][]IssuerSignedItem

// ValidityInfo is the validityInfo map of the MSO.
type ValidityInfo struct {
	Signed     time.Time
	ValidFrom  time.Time
	ValidUntil time.Time
}

// MobileSecurityObject is the decoded Mobile Security Object. Only the fields
// needed for verifier-side response validation are modelled.
type MobileSecurityObject struct {
	// DocType is the docType claim of the MSO (MSO key 0).
	DocType string
	// DigestAlgorithm is the value of the digestAlgorithm claim, e.g.
	// "SHA-256" or "SHA-384". It is passed verbatim to the Hasher callback.
	DigestAlgorithm string
	// ValueDigests maps namespace -> digestID -> expected digest, as declared
	// by the MSO valueDigests claim.
	ValueDigests map[string]map[uint64][]byte
	ValidityInfo ValidityInfo
	// DeviceKey is the issuer-certified device public key (COSE_Key). It is
	// opaque to this package and handed back to the DeviceSignatureVerifier.
	DeviceKey any
}

// IssuerSigned is the decoded IssuerSigned object of the response.
type IssuerSigned struct {
	NameSpaces IssuerNameSpaces
	MSO        MobileSecurityObject
}

// DeviceAuth carries the opaque device authentication structure.
//
// DeviceAuthCOSE is the raw CBOR encoding of the COSE_Sign1 object
// (with or without the surrounding tag 18); it is passed unchanged to the
// DeviceSignatureVerifier callback.
type DeviceAuth struct {
	DeviceAuthCOSE []byte
}

// DeviceSigned is the decoded DeviceSigned object of the response.
type DeviceSigned struct {
	// NameSpaces is the decoded deviceNameSpaces map, used only for
	// canonical re-encoding into the DeviceAuthentication structure.
	NameSpaces map[string]map[string]any
	// NameSpacesRaw, when non-nil, is the exact CBOR byte string that was
	// carried on the wire and is embedded verbatim in DeviceAuthentication.
	// When nil the decoded NameSpaces are canonical-encoded instead. A nil
	// map (no device namespaces) encodes as CBOR null, matching 18013-5.
	NameSpacesRaw []byte
	DeviceAuth    DeviceAuth
}

// Response is the full decoded mdoc response handed to VerifyResponse.
type Response struct {
	// DocType is the docType of the returned document.
	DocType string
	IssuerSigned
	DeviceSigned
}

// Hasher returns the hash.Hash implementing the named MSO digest algorithm
// (e.g. "SHA-256"). Returning an error rejects the response.
type Hasher func(algorithm string) (HasherSize, error)

// HasherSize combines the standard hash.Hash interface with a Size method,
// which hash.Hash already provides; the alias documents the contract.
type HasherSize interface {
	Write(p []byte) (n int, err error)
	Sum(b []byte) []byte
	Reset()
	Size() int
	BlockSize() int
}

// DeviceSignatureVerifier verifies the device signature.
//
// deviceKey is the public key taken from the MSO. deviceAuthCOSE is the raw
// COSE_Sign1 structure from the response and deviceAuthentication is the
// canonical CBOR encoding of
//
//	["DeviceAuthentication", SessionTranscript, DocType, DeviceNameSpacesBytes]
//
// which must be authenticated as the COSE_Sign1 payload. A nil error means
// the signature is valid for deviceAuthentication.
type DeviceSignatureVerifier func(deviceKey any, deviceAuthCOSE, deviceAuthentication []byte) error

// Options binds the verifier-local inputs and cryptographic callbacks.
type Options struct {
	// SessionTranscript are the raw SessionTranscript bytes generated by this
	// verifier for its own session. They are embedded into the
	// DeviceAuthentication structure that the device signature is checked
	// against, which defeats relaying a response captured in another session.
	SessionTranscript []byte
	// Requested is the set of data elements this verifier requested.
	Requested []RequestedElement
	// Now is the reference time for the MSO validity window check. The zero
	// value means time.Now().
	Now time.Time

	NewHash               Hasher
	VerifyDeviceSignature DeviceSignatureVerifier
}

// Sentinel errors returned by VerifyResponse. Wrapped contextual errors can be
// matched with errors.Is.
var (
	// ErrInvalidResponse is returned for malformed top-level inputs.
	ErrInvalidResponse = sentinel("netsec: invalid mdoc response")
	// ErrMissingCallback indicates a required cryptographic callback is nil.
	ErrMissingCallback = sentinel("netsec: missing hasher or device signature verifier")
	// ErrSessionTranscript is returned when the verifier has no local
	// SessionTranscript to bind the device signature to.
	ErrSessionTranscript = sentinel("netsec: missing verifier session transcript")
	// ErrDocTypeMismatch indicates the response docType differs from the MSO.
	ErrDocTypeMismatch = sentinel("netsec: response docType does not match MSO docType")
	// ErrExpired indicates the reference time is outside [validFrom, validUntil).
	ErrExpired = sentinel("netsec: MSO validity window does not cover current time")
	// ErrNotRequested indicates a returned data element was not requested.
	ErrNotRequested = sentinel("netsec: returned element is not part of the request")
	// ErrDigestNotFound means the MSO has no digest for the returned digestID.
	ErrDigestNotFound = sentinel("netsec: digestID not present in MSO valueDigests")
	// ErrDigestMismatch means the recomputed digest differs from the MSO one.
	ErrDigestMismatch = sentinel("netsec: recomputed digest does not match MSO")
	// ErrDuplicateDigestID means the same digestID occurs more than once in
	// one returned namespace.
	ErrDuplicateDigestID = sentinel("netsec: duplicate digestID in response")
	// ErrShortRandom means a returned item carries fewer than 16 random bytes.
	ErrShortRandom = sentinel("netsec: random must be at least 16 bytes")
	// ErrDeviceSignature means the device signature failed verification.
	ErrDeviceSignature = sentinel("netsec: device signature verification failed")
)

type sentinel string

func (e sentinel) Error() string { return string(e) }
