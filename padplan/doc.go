// Package padplan 为加密存储宿主规划确定性的桶填充方案。
//
// 背景：加密隐藏了对象内容，但每次读取暴露的块数（桶大小）仍可被观察。
// 本包根据对象长度分布、允许的桶边界和总填充字节预算，为每个对象选择一个
// 不小于其真实长度的桶，按字典序优化：
//
//  1. 最小化可观察到的不同桶大小数量；
//  2. 在桶数量相同的前提下最小化总填充字节。
//
// PlanBuckets 是纯函数：不读取也不修改任何实际存储对象；失败时返回 nil 方案
// 和错误，调用方不得据此改动对象。规划结果会经过全分配枚举（带预算与剪枝）
// 独立核对，并返回可审计的枚举证据。
