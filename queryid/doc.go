// Package queryid 为统计宿主提供匿名查询的缓存身份。
//
// 匿名查询缓存必须绑定真实分组边界：若扩大范围的请求复用了
// 已加噪的结果，就形成差分泄漏。本包把一次查询的身份拆成
// 两部分：
//
//   - 域（Domain）：有限集合表达式（并/交/差/补，作用在命名
//     基本集合上）。语义等价的表达式被规范化为同一个键——
//     交换律、结合律、分配律、德摩根律、吸收律以及无影响
//     原子的消除都通过真值表规范化完成。
//   - 机制（Mechanism）：聚合种类与有理参数、邻接定义、
//     裁剪规则与噪声代次。只有完全同机制的查询才共享缓存
//     结果；任一字段不同即得到不同的缓存键。
