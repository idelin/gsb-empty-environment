// Package coververify 提供安全测试插件上报协议的状态转换覆盖核验能力。
//
// 覆盖不能仅凭插件“声明访问过某个状态”计入。插件必须为每一次状态转换提交回执
// [Receipt]，回执携带四要素：前状态摘要、实际输入摘要、输出摘要和模型版本。
// 核验器 [Verifier] 调用宿主注册的确定性转换回调 [OracleFunc] 重放该转换，仅当
// 前状态位于同一模型版本的已核验链上、且重放输出与回执输出完全一致时，才把该
// 转换边计为已覆盖。
//
// 核验纪律：
//   - 断链（前状态未知或尚未核验）的回执保留为 [StatusPending]，不丢弃，链补齐后
//     自动重新核验；
//   - 同一转换边（模型版本+前状态+输入）出现互异输出时判定冲突，整条边隔离为
//     [StatusConflict]，不计覆盖，其下游转换回到断链待定；
//   - 重放输出与回执不一致为 [StatusMismatch]，转换回调返回错误或 panic 为
//     [StatusErrored]，二者都不计覆盖，回调修复后可重新核验；
//   - 内容相同的重复回执只识别不重复计数，跨模型拼接的链因模型版本隔离无法续接。
