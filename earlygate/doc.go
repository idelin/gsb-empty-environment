// Package earlygate 为请求宿主提供早期数据（类 0-RTT）副作用门控。
//
// 握手完成前到达的请求属于早期数据。宿主把每一批已解析操作通过
// [Gate.SubmitBatch] 提交给门控，门控调用调用方提供的 [Classifier] 得到每个
// 操作“不可变”的分类（只读性、可重放性与身份需求），并据此做出决策：
//
//   - 仅当操作无副作用、可安全重放，且身份需求不依赖握手时，才允许在握手
//     未完成阶段作为早期数据执行（[ExecuteEarly]）；
//   - 其余操作在早期阶段保持挂起（[HoldEarly]），握手确认后作为普通请求
//     派发（[DispatchNormal]）；
//   - 握手被拒绝时，挂起操作一律失败（[RejectRequest]）；任何已经早期执行
//     的操作都进入未确认状态，绝不会被当作普通请求再次派发。
//
// 事件模型
//
// 门控内核是一个纯事件归约器：输入为 [Event]（分批解析、分类器替换、握手
// 确认/拒绝、早期执行完成、单请求取消），输出为 [Decision] 决策序列。
// [Gate] 在其上提供互斥保护与决策回调，使宿主可以并发提交事件，同时在测试
// 中确定性地重放分批解析、分类更新以及确认与取消竞争等场景。
//
// 分类在操作首次提交时计算一次并复制保存，此后分类器替换只影响新提交的
// 操作，不会回溯修改任何既有请求，因此每个请求的分类都是不可变的。
