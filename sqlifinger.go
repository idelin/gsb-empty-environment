// Package sqlifinger 为 WAF 提供 SQL 注入词法指纹检测。
//
// 传统 WAF 按关键词黑名单拦截，容易被注释替换空白（1'/**/OR/**/1=1）、
// 嵌套括号（AND((1)=(1))）、大小写拼接（UnIoN SeLEcT）等手段绕过。
// 本组件改为按 MySQL 方言对参数值切词——正确识别各类注释、带转义的
// 字符串、反引号标识符与十六进制字面量——再把 token 折叠成词类序列，
// 与可配置的危险指纹做子序列匹配。检测时分别按不在引号内、单引号内、
// 双引号内三种起始上下文切词，任一命中即判定为注入。
