"""Symmetry reduction over place permutations.

A symmetry generator is a place permutation that is verified to be a net
automorphism: capacities are preserved and the multiset of transition
signatures (all four arc kinds) is preserved.  Because arc structure --
including read and inhibitor arcs -- is preserved exactly, enabling
conditions are identical for symmetric transitions; the reduction never
changes which transitions are enabled at a symmetric marking.

The reduced search stores one representative per symmetry orbit (the
lexicographically smallest marking).  Representatives are real markings
over real place ids, so counterexamples found in the reduced search replay
directly on the original net.
"""
from __future__ import annotations

from collections import Counter

MAX_GROUP_SIZE = 100000


def verify_symmetry(net, perm):
    """True iff perm (dict place_id -> place_id) is a net automorphism."""
    if set(perm.keys()) != set(net.places):
        return False
    if sorted(perm.values()) != sorted(net.places):
        return False
    for pid, image in perm.items():
        if net.places[pid].capacity != net.places[image].capacity:
            return False

    def mapped_signature(t):
        def m(d):
            return tuple(sorted((perm[k], v) for k, v in d.items()))
        return (m(t.inputs), m(t.outputs), m(t.read), m(t.inhibitor))

    original = Counter(t.signature() for t in net.transitions.values())
    image = Counter(mapped_signature(t) for t in net.transitions.values())
    return original == image


def as_index_perm(net, perm):
    """Convert a place permutation to index form: ip[new] = old."""
    ip = [0] * len(net.place_order)
    for pid, image in perm.items():
        ip[net.index[image]] = net.index[pid]
    return tuple(ip)


def apply_perm(marking, index_perm):
    out = [0] * len(marking)
    for new_i, old_i in enumerate(index_perm):
        out[new_i] = marking[old_i]
    return tuple(out)


def _compose(a, b):
    return tuple(a[b[i]] for i in range(len(a)))


def group_closure(net, generators):
    """Full permutation group (index form) generated by `generators`."""
    identity = tuple(range(len(net.place_order)))
    gens = [as_index_perm(net, g) for g in generators]
    perms = {identity}
    frontier = [identity]
    while frontier:
        p = frontier.pop()
        for g in gens:
            q = _compose(p, g)
            if q not in perms:
                if len(perms) >= MAX_GROUP_SIZE:
                    raise ValueError("symmetry group too large")
                perms.add(q)
                frontier.append(q)
    return sorted(perms)


def canonical(marking, perms):
    """Orbit representative: lexicographically smallest symmetric image."""
    return min(apply_perm(marking, p) for p in perms)


def cross_check(net, initial, generators, limits=None):
    """Independent non-reduced search vs. symmetry-reduced search.

    Returns a dict with both results and whether the orbit sets of the
    reachable markings agree.  Use on small nets to validate the reduction.
    """
    from .reachability import search

    for g in generators:
        if not verify_symmetry(net, g):
            raise ValueError(f"not a net automorphism: {g!r}")
    perms = group_closure(net, generators)
    full = search(net, initial, limits=limits)
    reduced = search(net, initial, limits=limits, perms=perms)
    full_orbits = {canonical(m, perms) for m in full.markings}
    reduced_orbits = {canonical(m, perms) for m in reduced.markings}
    return {
        "match": full_orbits == reduced_orbits,
        "full_states": len(full.markings),
        "reduced_states": len(reduced.markings),
        "orbits": len(full_orbits),
        "full": full,
        "reduced": reduced,
    }
