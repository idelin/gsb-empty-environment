package refresh_test

import (
	"errors"
	"math/big"

	"prescreen.local/ddd-9449-20261122-v2/refresh"
)

var errBadPoint = errors.New("bad point encoding")

// addPoint is a group element of the additive reference group Z_p under
// addition mod p. Every operation is a plain modular integer, so the whole
// "group" is transparent and auditable by hand in tests.
type addPoint struct{ v *big.Int }

func (p addPoint) Equals(other refresh.Point) bool {
	o, ok := other.(addPoint)
	return ok && p.v.Cmp(o.v) == 0
}

func (p addPoint) Marshal() ([]byte, error) {
	return append([]byte("A:"), p.v.Bytes()...), nil
}

// AdditiveGroup is the transparent additive reference group over field f.
type AdditiveGroup struct{ p *big.Int }

func NewAdditiveGroup(p *big.Int) *AdditiveGroup { return &AdditiveGroup{p: p} }

func (g *AdditiveGroup) Generator() refresh.Point { return addPoint{big.NewInt(1)} }

func (g *AdditiveGroup) Identity() refresh.Point { return addPoint{big.NewInt(0)} }

func (g *AdditiveGroup) ScalarBaseMul(s *big.Int) refresh.Point {
	return addPoint{new(big.Int).Mod(new(big.Int).Set(s), g.p)}
}

func (g *AdditiveGroup) ScalarMul(pt refresh.Point, s *big.Int) refresh.Point {
	a := pt.(addPoint).v
	return addPoint{new(big.Int).Mod(new(big.Int).Mul(a, s), g.p)}
}

func (g *AdditiveGroup) Add(a, b refresh.Point) refresh.Point {
	return addPoint{new(big.Int).Mod(new(big.Int).Add(a.(addPoint).v, b.(addPoint).v), g.p)}
}

func (g *AdditiveGroup) Neg(pt refresh.Point) refresh.Point {
	return addPoint{new(big.Int).Mod(new(big.Int).Neg(pt.(addPoint).v), g.p)}
}

func (g *AdditiveGroup) ParsePoint(b []byte) (refresh.Point, error) {
	if len(b) < 2 || b[0] != 'A' || b[1] != ':' {
		return nil, errBadPoint
	}
	v := new(big.Int).SetBytes(b[2:])
	v.Mod(v, g.p)
	return addPoint{v}, nil
}

// mulPoint is an element of the multiplicative subgroup <g> of F_p^*.
type mulPoint struct{ v *big.Int }

func (p mulPoint) Equals(other refresh.Point) bool {
	o, ok := other.(mulPoint)
	return ok && p.v.Cmp(o.v) == 0
}

func (p mulPoint) Marshal() ([]byte, error) {
	return append([]byte("M:"), p.v.Bytes()...), nil
}

// MultiplicativeGroup is a second transparent reference: the prime-order
// cyclic subgroup generated by base in F_p^*. Scalars live in a prime field
// whose modulus equals the subgroup order, so exponent arithmetic matches the
// scalar field exactly.
type MultiplicativeGroup struct {
	p    *big.Int
	base *big.Int
	ord  *big.Int
}

func NewMultiplicativeGroup(p, base, order *big.Int) *MultiplicativeGroup {
	return &MultiplicativeGroup{p: p, base: new(big.Int).Set(base), ord: order}
}

func (g *MultiplicativeGroup) Generator() refresh.Point {
	return mulPoint{new(big.Int).Set(g.base)}
}

func (g *MultiplicativeGroup) Identity() refresh.Point { return mulPoint{big.NewInt(1)} }

func (g *MultiplicativeGroup) ScalarBaseMul(s *big.Int) refresh.Point {
	return g.ScalarMul(g.Generator(), s)
}

func (g *MultiplicativeGroup) ScalarMul(pt refresh.Point, s *big.Int) refresh.Point {
	exp := new(big.Int).Mod(s, g.ord)
	return mulPoint{new(big.Int).Exp(pt.(mulPoint).v, exp, g.p)}
}

func (g *MultiplicativeGroup) Add(a, b refresh.Point) refresh.Point {
	return mulPoint{new(big.Int).Mod(new(big.Int).Mul(a.(mulPoint).v, b.(mulPoint).v), g.p)}
}

func (g *MultiplicativeGroup) Neg(pt refresh.Point) refresh.Point {
	return mulPoint{new(big.Int).ModInverse(pt.(mulPoint).v, g.p)}
}

func (g *MultiplicativeGroup) ParsePoint(b []byte) (refresh.Point, error) {
	if len(b) < 2 || b[0] != 'M' || b[1] != ':' {
		return nil, errBadPoint
	}
	v := new(big.Int).SetBytes(b[2:])
	if v.Sign() == 0 || v.Cmp(g.p) >= 0 {
		return nil, errBadPoint
	}
	return mulPoint{v}, nil
}
