#!/usr/bin/env python3.11
"""Finite-domain counterexample shrinker for integer vectors.

Given an integer vector and a deterministic failing predicate, shrink the
vector using only two kinds of moves:

  * delete an element, or
  * decrease the absolute value of an element by 1 (sign is preserved;
    a move never changes the sign of an element and never crosses zero).

The search objective is lexicographic on the cost tuple

    (length, sum of absolute values, vector in lexicographic order)

i.e. shorter is better, then smaller absolute sum, then lexicographically
smaller vector.

The search enumerates the finite reachable state space with a best-first
priority queue ordered by the cost tuple.  Two activities are separated:

  * expansion (generating neighbours) is free -- it costs no predicate
    calls, because a cheap state can hide behind an expensive ancestor
    (e.g. [-1, -1] is only generated by expanding [-2, -1]);
  * evaluation (calling the predicate) happens only for states whose
    cost is strictly smaller than the best failing state found so far.

Minimality is proven only when the queue is drained, i.e. every reachable
state has been expanded and every reachable state cheaper than the
reported result has been evaluated and none of them fails.  If the
predicate-call budget runs out first, the result is reported as NOT
proven and the unexplored frontier is returned -- a local minimum is
never dressed up as a global one.

All predicate results are memoised so the predicate is never evaluated
twice on the same vector.

Usage:
    python3.11 shrinker.py --predicate consecutive_equal_nonzero <<<'[4, 4, 9]'
    python3.11 shrinker.py --predicate any_nonzero --budget 500 < input.json

Input (stdin or --input file): a JSON array of integers, or a JSON object
{"vector": [...], "budget": N}.  Output: a JSON report (see README.md).
"""

from __future__ import annotations

import argparse
import heapq
import json
import sys
from typing import Callable, Iterator

Predicate = Callable[[list[int]], bool]
State = tuple[int, ...]


# --------------------------------------------------------------------------
# Built-in deterministic predicates (all operate on synthetic data only).
# --------------------------------------------------------------------------

def pred_consecutive_equal_nonzero(v: list[int]) -> bool:
    """True iff two adjacent elements are equal and non-zero."""
    return any(v[i] == v[i + 1] != 0 for i in range(len(v) - 1))


def pred_any_nonzero(v: list[int]) -> bool:
    """True iff at least one element is non-zero."""
    return any(x != 0 for x in v)


def pred_zero_sum_pair(v: list[int]) -> bool:
    """True iff two distinct non-zero elements sum to zero."""
    return any(
        v[i] != 0 and v[i] + v[j] == 0
        for i in range(len(v))
        for j in range(i + 1, len(v))
    )


def pred_sum_at_least_ten(v: list[int]) -> bool:
    """True iff the sum of the vector is >= 10."""
    return sum(v) >= 10


PREDICATES: dict[str, Predicate] = {
    "consecutive_equal_nonzero": pred_consecutive_equal_nonzero,
    "any_nonzero": pred_any_nonzero,
    "zero_sum_pair": pred_zero_sum_pair,
    "sum_at_least_ten": pred_sum_at_least_ten,
}


# --------------------------------------------------------------------------
# Core shrinker.
# --------------------------------------------------------------------------

def cost(state: State) -> tuple[int, int, State]:
    """Objective tuple: (length, sum of |x|, lexicographic order)."""
    return (len(state), sum(abs(x) for x in state), state)


def neighbors(state: State) -> Iterator[State]:
    """All states reachable in one legal move (each strictly cheaper)."""
    for i in range(len(state)):
        yield state[:i] + state[i + 1 :]  # delete element i
    for i, x in enumerate(state):
        if x > 0:
            yield state[:i] + (x - 1,) + state[i + 1 :]
        elif x < 0:
            yield state[:i] + (x + 1,) + state[i + 1 :]


def shrink(
    vector: list[int],
    predicate: Predicate,
    budget: int,
    frontier_sample_size: int = 10,
) -> dict:
    """Shrink ``vector`` while ``predicate`` keeps failing.

    Returns a report dict.  ``proven_minimal`` is True only when every
    reachable state cheaper than the reported result has been evaluated
    and none of them fails -- i.e. the result is the global minimum, not
    merely a local one.  When the budget is exhausted first,
    ``proven_minimal`` is False and ``frontier_*`` fields describe the
    boundary of the unexplored search space.
    """
    start: State = tuple(int(x) for x in vector)
    cache: dict[State, bool] = {}
    calls = 0

    def evaluate(state: State) -> bool:
        nonlocal calls
        if state not in cache:
            cache[state] = bool(predicate(list(state)))
            calls += 1
        return cache[state]

    heap: list[tuple[tuple[int, int, State], State]] = [(cost(start), start)]
    seen: set[State] = {start}
    best: State | None = None
    proven = False
    budget_exhausted = False
    explored = 0

    while heap:
        key, state = heapq.heappop(heap)
        # Expansion is free: cheaper states may be reachable only through
        # more expensive ancestors, so neighbours are always generated.
        for nxt in neighbors(state):
            if nxt not in seen:
                seen.add(nxt)
                heapq.heappush(heap, (cost(nxt), nxt))
        if best is not None and key >= cost(best):
            continue  # cannot beat the current best; no need to evaluate
        if state not in cache and calls >= budget:
            budget_exhausted = True
            heapq.heappush(heap, (key, state))  # keep it in the frontier
            break
        explored += 1
        if evaluate(state):
            # Failing states are evaluated in non-decreasing cost order,
            # so a later failure can only improve on ``best`` if it is
            # strictly cheaper (late-generated states can arrive out of
            # order, so keep the cheaper one explicitly).
            if best is None or key < cost(best):
                best = state
    else:
        # Queue drained: every reachable state was expanded and every
        # reachable state cheaper than ``best`` was evaluated.  This is
        # the only path that may claim a proven global minimum.
        proven = True

    if best is not None:
        frontier = [s for k, s in heap if k < cost(best)]
    else:
        frontier = [s for _, s in heap]
    frontier.sort(key=cost)

    return {
        "input": list(start),
        "result": list(best) if best is not None else None,
        "proven_minimal": proven,
        "budget": budget,
        "budget_exhausted": budget_exhausted,
        "predicate_calls": calls,
        "cache_entries": len(cache),
        "states_explored": explored,
        "frontier_size": len(frontier),
        "frontier_sample": [list(s) for s in frontier[:frontier_sample_size]],
        "note": (
            "global minimum proven"
            if proven and best is not None
            else "no failing state reachable from input"
            if proven
            else "NOT proven minimal: predicate budget exhausted; "
            "result is only the best failing state found so far"
        ),
    }


# --------------------------------------------------------------------------
# Command line interface.
# --------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Finite-domain counterexample shrinker for integer "
        "vectors. Moves: delete an element, or decrease |x| by 1 "
        "(sign preserved). Objective: (length, sum|x|, lexicographic)."
    )
    parser.add_argument(
        "--predicate",
        required=True,
        choices=sorted(PREDICATES),
        help="name of the built-in deterministic failing predicate",
    )
    parser.add_argument(
        "--budget",
        type=int,
        default=None,
        help="max number of predicate evaluations (overrides input file)",
    )
    parser.add_argument(
        "--input",
        default=None,
        help="JSON input file (default: read stdin)",
    )
    args = parser.parse_args(argv)

    raw = open(args.input, encoding="utf-8").read() if args.input else sys.stdin.read()
    data = json.loads(raw)
    if isinstance(data, list):
        vector, budget = data, 10_000
    elif isinstance(data, dict) and isinstance(data.get("vector"), list):
        vector = data["vector"]
        budget = int(data.get("budget", 10_000))
    else:
        parser.error("input must be a JSON array of ints or "
                     '{"vector": [...], "budget": N}')
    if args.budget is not None:
        budget = args.budget
    if not all(isinstance(x, int) and not isinstance(x, bool) for x in vector):
        parser.error("vector elements must be integers")

    report = shrink(vector, PREDICATES[args.predicate], budget)
    report["predicate"] = args.predicate
    json.dump(report, sys.stdout, indent=2, ensure_ascii=False)
    sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
