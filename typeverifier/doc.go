// Package typeverifier 为 Go 字节码加载宿主提供基于抽象解释的引用类型验证。
//
// 它只消费宿主已解码的指令数组与异常表（见 Instruction、Handler、Method），
// 不解析完整 class 文件。类继承由宿主以 Object 为根的有限单继承树提供（见 Hierarchy）。
//
// 抽象值分为三类：
//   - 不可用值（top）：局部槽合流不相容，或被构造失败的异常边置失效；
//   - 已初始化引用：携带静态类型，合流时取最近公共祖先；
//   - 未初始化引用：携带产生它的 new 指令 ID 与类，两个 new 即便同类也是不同身份。
//
// 关键安全规则：
//   - init 只接受同类未初始化接收者；正常边把帧中同一 new 身份的全部别名改为已初始化；
//   - init 的异常边把局部槽中该身份别名（含父/子类残留）置不可用，清空栈并压入
//     已初始化 Throwable，杜绝构造失败对象沿异常边变成可调用引用；
//   - new 的异常边不产生对象；
//   - throw 必须接收已初始化 Throwable；use 要求已初始化且类型可赋给所需类；
//   - 局部槽合流不相容置不可用，操作数栈合流不相容（含长度不一致）直接拒绝；
//   - 回边携带未初始化引用一律拒绝；return 要求操作数栈为空。
//
// Verify 运行工作表（worklist）不动点，覆盖包括异常边在内的所有可达边，
// 并通过 VerifyError 返回首个拒绝点与从入口出发的拒绝路径。
