// Package pseudonym 为脱敏服务分配稳定、可碰撞隔离的伪名（短码）。
//
// 背景：把标识符截短成短码会发生碰撞，若直接按短码合并，两个人的事件
// 会被串接到一起。本包用三层设计解决该问题：
//
//   - 短码只是索引：短码是完整 HMAC 摘要的无填充 base32 前缀，仅用于
//     快速查找，绝不单独用于判定身份。
//   - 完整 HMAC 确认身份：每个伪名同时持久化完整摘要，Confirm 用恒定时间
//     比较完整摘要，短码命中而摘要不符时拒绝，事件不会被误并。
//   - 碰撞扩展且不改变已发布短码：新身份从最短前缀开始尝试，占用即向后
//     扩展一个字符，直到找到空闲前缀；已发布短码永不更换，重复分配幂等。
//
// 为了让碰撞发生前写入的旧事件仍可查询，分配器维护显式别名关系：
// 新身份在最初发布的最短码（碰撞码）下登记一条 collision_extension 别名，
// Resolve 会同时返回当前持有者与全部别名身份，调用方再用完整摘要区分。
// 历史迁移数据可通过 AddAlias 登记 legacy_migration 别名。
//
// 并发与持久化：Allocate 在互斥区内完成“选码 + 落盘 + 更新索引 + 写别名”，
// 对调用方表现为原子操作。Store 是追加式记录；WALStore 以 JSON Lines 落盘
// 并 fsync，重启时回放，末尾缺换行的半行按未提交写入丢弃，已提交区域损坏
// 则返回 ErrCorrupt，避免静默丢失数据。
