"""运行样例：十字交叉、完全重合、部分重叠、有理数交点、零长度段。"""

import json

from planar_segments import build_planar_graph, graph_to_dict

SAMPLES = {
    "十字交叉（应得 5 顶点 4 子边）": [
        [[0, 0], [4, 4]],
        [[0, 4], [4, 0]],
    ],
    "完全重合（1 条子边，双来源）": [
        [[0, 0], [4, 0]],
        [[0, 0], [4, 0]],
    ],
    "共线部分重叠（3 条子边，中段双来源）": [
        [[0, 0], [6, 0]],
        [[3, 0], [9, 0]],
    ],
    "有理数交点 (1/2, 1/2)": [
        [[0, 0], [1, 1]],
        [[0, 1], [1, 0]],
    ],
    "共享端点去重 + 零长度段": [
        [[0, 0], [2, 0]],
        [[2, 0], [2, 2]],
        [[2, 0], [2, 0]],   # 落在已有顶点上
        [[1, 0], [1, 0]],   # 落在子边内部
        [[9, 9], [9, 9]],   # 孤立点
    ],
    "T 型接触 + 有理数重叠端点": [
        [["0", "0"], ["5/2", "0"]],
        [["5/2", "0"], ["5/2", "3"]],
        [["1/2", "0"], ["7/4", "0"]],
    ],
}

for title, segments in SAMPLES.items():
    print(f"=== {title} ===")
    graph = build_planar_graph(segments)
    print(json.dumps(graph_to_dict(graph), ensure_ascii=False, indent=2))
    print()
