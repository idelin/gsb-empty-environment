// Package undocrdt implements a distributed undo/redo tree for collaborative
// editing. The document is an RGA-style sequence CRDT: every character is a
// node with a globally unique ID and a left-origin pointer, so concurrent
// inserts merge deterministically on every replica.
//
// Undo and redo never rewrite history. Instead they append reverse
// compensation nodes (Delete/Restore) to the operation graph, each carrying
// an Undoes edge to the node it reverses. The nodes plus edges form the
// undo tree, and topological validity is preserved because compensation
// nodes are ordinary CRDT operations that commute with concurrent edits
// from other collaborators.
package undocrdt

// OpID uniquely identifies an operation and, for inserts, its first
// character. The (Site, Seq) pair is globally unique because each site
// allocates Seq from its own monotonic counter.
type OpID struct {
	Site string
	Seq  int
}

// IsRoot reports whether id refers to the virtual root of the document
// (the position before the first character).
func (id OpID) IsRoot() bool { return id.Seq == 0 }

// RootID is the left-origin of an insert at the very start of the document.
var RootID = OpID{}

// Kind is the operation type stored in the undo tree.
type Kind int

const (
	// Insert is a user edit that appends new characters after a left-origin.
	Insert Kind = iota
	// Delete removes characters. It is either a user edit or a
	// compensation node generated by Undo of an Insert.
	Delete
	// Restore revives previously deleted characters. It is a compensation
	// node generated by Undo of a Delete or by Redo of an Insert.
	Restore
)

func (k Kind) String() string {
	switch k {
	case Insert:
		return "Insert"
	case Delete:
		return "Delete"
	case Restore:
		return "Restore"
	}
	return "Unknown"
}

// Op is a node of the undo tree. Every state change, including undo and
// redo, is materialized as a new Op so the graph only ever grows.
type Op struct {
	ID   OpID
	Kind Kind

	// After is the left-origin of the insert (Insert only).
	After OpID
	// Text is the inserted payload (Insert only). Character i of Text has
	// ID {ID.Site, ID.Seq + i}.
	Text string

	// Targets are the character IDs a Delete/Restore applies to.
	Targets []OpID

	// Undoes is the undo-tree edge: the node this compensation reverses.
	// Zero for plain user edits.
	Undoes OpID
}

// CharIDs returns the character IDs created by an Insert op.
func (op Op) CharIDs() []OpID {
	ids := make([]OpID, 0, len([]rune(op.Text)))
	for i := range []rune(op.Text) {
		ids = append(ids, OpID{Site: op.ID.Site, Seq: op.ID.Seq + i})
	}
	return ids
}

// IsCompensation reports whether the op was generated by Undo/Redo.
func (op Op) IsCompensation() bool { return !op.Undoes.IsRoot() }
