// Package netsec 为主机策略宿主提供安全标记降级的路径验证。
//
// 标签集合构成有限偏序（见 Poset），级别越高位置越高，例如
// 公开 < 内部 < 机密。普通操作只允许不降级：标签不变或沿偏序升级直接
// 放行；严格降级只能通过已声明的审核转换边（Transition）完成，转换边
// 绑定授权主体与前置证据。证据为跨事件共享资源，带最大消费次数
// （EvidenceSpec.Capacity），每次使用转换边即消费一次。
//
// Validator.Verify 对事件轨迹做小状态枚举：状态为各证据的剩余次数
// 向量，每个事件在所有可达状态上枚举可成立的转换并去重展开。任一状态
// 走通即合法；全部状态失败时返回首个无合法证明的事件 Violation 及其
// 缺失条件（无转换边、主体未授权或证据耗尽）。
