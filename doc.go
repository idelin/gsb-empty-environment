// Package netsec 为发布宿主提供准标识泛化分组的隐私核验能力。
//
// 仅满足 k-匿名的组大小并不能阻止敏感属性单一泄漏：一个同构组即使足够大，
// 若组内敏感值只有一种，攻击者仍可确定目标的敏感属性。本包在组大小之外
// 同时强制执行两条 l-多样性约束：
//
//   - 每个泛化组内“已知”敏感值至少有 L 个不同类别；
//   - 任一已知敏感值在组内的占比不超过给定的有理阈值（math/big.Rat 精确比较）。
//
// 未知敏感值（默认空字符串，可用 Config.UnknownSentinel 自定义）代表真实
// 记录但不携带可泄漏类别：它既不参与 L 种类计数，也不进入占比分子，绝不被
// 当成一个普通类别凑数。占比分母口径可在 RatioOverAll（全组记录，默认、更
// 严格）与 RatioOverKnown（仅已知记录，经典口径）之间显式选择。
//
// 典型用法是先用 NewTree 构建每个准标识的泛化树，再以 Config 创建 Verifier，
// Replace 装载记录后调用 RegroupAndVerify 取得 Report；撤回记录时调用
// Withdraw，它会对剩余全量数据重新泛化分组，并返回与上一份报告逐组对照的
// UpdateResult。Report.MinimalViolation 返回规模最小的违规组及其最小证据：
// 多样性证据是每个已知值各一条记录的代表集，占比证据给出越界值的精确比值、
// 阈值与全部成员记录 ID。
