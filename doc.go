// 核心安全约束：
//   - 每一跳都记录查询类型、产生应答的权威区以及有效期（含绝对失效时刻）。
//   - 拒绝 CNAME 循环，以及同一名字在有效期内相互矛盾的别名指向。
//   - 否定结论严格限定作用域：NODATA 只否定被证明名字的同一类型，
//     NXDOMAIN 只覆盖被证明名字本身及其下属，绝不向上套到起始名字。
//   - 途中超时等失败通过 IncompleteChainError 返回已确认的部分信任路径，
//     绝不把解析失败伪装成“名字不存在”。
