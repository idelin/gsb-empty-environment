// Package cursorpage 实现面向远端列表采集的断点续传读取器。
//
// 核心机制：
//   - 游标模式下按服务端不透明游标 keyset 翻页，断点原子落盘，内容包含
//     服务端游标、已发出的最后一个键及其版本、本页已交付位置；
//   - 恢复时按 (Key, Version) 去重，同一版本绝不重复交付，漏在游标外的
//     数据由去重表和回溯窗口兜底，保证每条存活记录至少交付一次；
//   - 服务端游标过期或游标自然耗尽时，退回到按 (UpdatedAt, Version)
//     升序的回溯窗口扫描，锚点为高水位减去可配置的重叠窗口；
//   - 断点通过“临时文件 + fsync + 原子 rename”写入单个文件，
//     任意时刻崩溃都只会留下完整的某一份状态。
