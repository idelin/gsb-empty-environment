// Package netsec 实现软 RNIC 的 RC 队列对入站报文准入。
//
// RoCE v2 的 RC 传输不具备加密认证，同一二层网络上的攻击者可以伪造源
// 地址并猜测 24 位 QPN/PSN 注入报文。本包在入站处理路径上提供三道独立
// 检查，缓解该注入面：
//
//   - 源 GID 必须等于连接建立（Connect）时登记的对端 GID；
//   - 目的 QPN 必须命中一个处于连接态的存活 QP；
//   - PSN 必须落在期望 PSN 的回绕窗口 [expected-w, expected+w] 内。
//
// PSN 越窗报文直接丢弃，累计达到配置阈值后 QP 转入 StateError，此后该
// QP 的一切报文都被拒绝。QPN 由加密随机源在 24 位空间内分配，QP 销毁后
// 其 QPN 进入隔离（静默）期，期满之前不会被重新分配，避免新连接收到
// 发往旧连接的滞留/伪造报文。
