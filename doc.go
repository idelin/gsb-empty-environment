// Package netsec 提供与服务安全策略绑定的 TLS 会话恢复票据封装。
//
// 票据使用标准库 AES-GCM（crypto/aes + crypto/cipher）密封，密文与附加
// 认证数据（AAD）共同绑定租户和密钥标识；票据明文（claims）绑定租户、
// 协议选项、客户端认证等级、签发时策略摘要、有效期和宿主会话数据。
//
// 恢复会话时 Manager 不会仅凭密文验证通过就放行，而是按以下顺序校验：
// AEAD 认证 → 租户一致性 → 票据有效期 → 当前策略 Policy.Allows 是否仍
// 允许票据记载的认证等级与协议选项。只有全部通过后才调用宿主提供的
// SessionFactory 重建会话，因此配置收紧后旧票据无法跳过新认证要求，
// 验证失败也不会产生任何会话。
//
// 密钥通过 Keyring 管理：轮换后旧密钥在配置的宽限期内仅用于解密历史
// 票据，超出宽限期即被移除，旧票据随之失效。
