// Package netsec 为 Snowflake 类桥接的经纪服务提供代理轮询与客户端
// offer 匹配的前缀限额能力，防止审查方通过批量部署代理并轮换代理标识
// 来枚举客户端。
//
// 核心规则见 [Limiter]：
//   - 每个代理来源前缀（IPv4 /24 或 IPv6 /48）在滚动一小时内最多收到
//     DefaultMaxClients 个不同客户端的 offer，与代理标识是否轮换无关；
//   - 同一客户端对同一前缀的重复投递只计一次；
//   - 限制型 NAT 的客户端只能匹配到非限制型 NAT 的代理，代理自报 NAT
//     与最近探测结果冲突时以探测结果为准；
//   - 每个 offer 最多交给一个代理；
//   - 达到限额的前缀在匹配时被静默跳过，不返回错误。
