// Package netsec 为办公文档导入服务提供 OPC 包校验组件。
//
// 组件解决三类不可信输入问题：
//
//   - 部件名：按 ECMA-376 Part 2（OPC）规则校验 Zip 包内条目，并对解码、
//     忽略大小写后重名的部件去重，防止互相覆盖。
//   - 关系目标：把 .rels 中的相对 Target 安全解析到包内部件，点段越界、
//     反斜线、编码分隔符一律拒绝；外部绝对 URI 仅在调用方显式允许时保留。
//   - OLE 包名：嵌入 OLE 对象携带的带路径原始文件名，只取最后一段并清洗
//     为安全文件名。
package netsec
