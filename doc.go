// Package netsec 为插件验证宿主提供仿射地址分析，证明所有数据读取都落在
// 宿主声明的内存区域内。
//
// 分析模型
//
// 基本块内只允许基址加常数（OpBase/OpAddConst）、寄存器复制（OpCopy）和
// 区间分支（TermBranch）三类地址相关操作，外加外部输入引入（OpInput）与
// 数据读取（OpLoad）。寄存器的抽象值 Affine 同时携带偏移整数区间和地址
// 来源集合：合流（join）对来源取并集、对同源偏移取区间包络，因此来源在
// 任意控制流合流后都不会丢失。
//
// 外部输入在引入时是无界顶，只能通过 TermBranch 表达的显式边界检查收窄；
// 未经收窄的外部值参与读取寻址会直接产生违例。
//
// 循环不做无界迭代推导，而是采用宿主在 Program.Invariants 中给定的循环头
// 不变量：分析器把不变量当作归纳假设，并对每条到达循环头的边做包含性
// （frameLeq）核对以验证保持性。
//
// 每条通过证明的读取输出一份 Certificate，给出来源集合、各来源绝对访问
// 区间与统一界。有限输入解释器（Run/EnumerateInputs）枚举声明输入域的
// 全部组合，CrossCheck 把具体读取与静态证书双向核对。
