// Package taskpkg 实现材质扫描中多灯未知曝光偏差与逐像素几何参数的
// 联合校准。
//
// 亮度模型（逐像素、逐灯）为
//
//	y_k = max(0, e_k * L_k · g)
//
// 其中 e_k 是第 k 盏灯的曝光（正有理数），L_k 是已知的三维有理光
// 向量，g = 反照率 * 单位法线 是三维向量。首灯曝光固定为 1，所有
// 像素共用同一个曝光向量；求解过程禁止为不同像素分别挑选各自最有
// 利的曝光。
//
// 对每个曝光向量、每个像素，枚举由该像素“非饱和”灯组成的满秩三灯
// 组，用精确有理数线性求解候选 g，再以给定的有理残差阈值挑选一致
// 观测最多、其次平方误差最小、再次三灯 ID 字典序最小的候选。全图
// 在所有曝光向量上先最大化一致观测总数、再最小化平方误差总和，平
// 局依次按曝光索引、各像素三灯 ID 决胜。
//
// 全部比较（残差阈值、排序、决胜）均使用 math/big 的精确有理运算。
// 饱和观测在任何候选评估之前显式排除，并出现在拒绝观测列表中。
