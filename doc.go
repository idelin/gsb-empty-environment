// Package netsec 提供有限布尔程序上的反例引导抽象精化（CEGAR）组件，
// 供静态分析宿主作为可导入库使用。
//
// 典型工作流见 Verify：
//
//   - 输入 Program（至多 MaxVariables 个布尔变量）与初始谓词集合；
//   - 在当前谓词抽象上做不动点可达分析，缓存节点级抽象摘要；
//   - 若错误节点抽象可达，沿候选反例路径用具体取值枚举判可行性；
//   - 伪反例触发 learnMinimalSeparator，学习区分冲突具体状态的最小
//     合取谓词，并由 rebuildSummaries 丢弃受影响区域摘要、无损重编码
//     其余摘要；
//   - 真实反例返回逐步具体见证；任何预算耗尽返回 Unknown。
//
// 事件流 Result.Events 按顺序记录抽象反例、伪反例、真实反例与精化，
// 便于宿主观察伪反例与真实反例交替出现的验证过程。
