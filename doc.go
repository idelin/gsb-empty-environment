// Package netsec 为主机取证宿主提供文件系统元数据一致性分析能力。
//
// 分析输入由三类证据构成：
//   - 目录引用图（ReferenceGraph）：描述根对象与目录项如何引用对象；
//   - 对象区段表（SegmentTable）：描述每个对象占用的数据块区段；
//   - 分配位图（AllocationBitmap）：描述每个块在设备上是否处于已分配状态。
//
// 同一块被多个对象共享只有在全部持有者都属于同一个非空受信共享组时才合法，
// 例如硬链接或克隆场景；不同共享组、或组外对象之间的任何重叠都按非法重叠报告。
//
// 分析入口为 Analyze，独立逐块重放验证入口为 VerifyBlockReferences。
package netsec
