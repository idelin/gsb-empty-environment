// Package netsec 实现 RSA-CRT 故障签名分析（Bellcore 风格）与本地小型
// CRT 签名器，供硬件签名回归台判断一次 CRT 计算故障是否足以泄露私钥因子。
//
// 分析入口为 NewAnalyzer，它先校验公开参数：N 必须是奇合数、1 < e < N。
// 每份样本要求 m、s 均为非负且小于 N，且 gcd(m,N)=1。分析时重算
// v = s^e mod N：v == m 记为正常签名；否则计算 g = gcd(v-m mod N, N)，
// 仅当 1 < g < N 时返回因子 g 与 N/g，并以乘积校验和素性证据做结构说明。
// 64 位以内使用确定性 Miller-Rabin 基集合 {2,3,5,7,11,13,17}；超出 64 位
// 时必须注入宿主素性回调，证据不足一律标注 unknown，绝不把合数称素数。
// g 为 1 或 N 时只记为无法由该样本分解，并继续处理其余样本。
//
// AnalyzePair 在同消息的正常/故障签名之间额外计算 gcd(s_good-s_bad, N)。
// 单分支 CRT 故障模型下两种方法必须给出同一因子，否则明确报告模型违背。
// AnalyzeBatch 对重复 (m,s) 去重，全零、异消息或自身不验签的样本都不会
// 造成假成功，失败样本以 Evidence 形式保留。
//
// CRTSigner 仅用于本地实验：在 p 支或 q 支的模幂余数上按调用方指定位置
// 翻转一个比特，再用 Garner 公式重组；故障位超出分支模数位宽时返回
// ErrFaultPosition，由调用方保留为无法注入/无法分解的证据。
