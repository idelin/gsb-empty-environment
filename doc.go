// Package netsec 组合并行安全检测器的判定结果。
//
// 策略把检测器划分为两组：
//   - 允许组：检测器给出已证明允许即累计，达到配置阈值且拒绝组全程无命中时放行；
//   - 拒绝组：任一检测器给出已证明拒绝即拒绝。拒绝优先，快速允许不能覆盖稍后
//     返回的关键拒绝。
//
// 尚未给出已证明结果的检测器处于未知状态。只有所有仍可能改变结论的分支都结束后
// 才能定案；当结论已被当前证据锁定时，[Combiner.Evaluate] 会给出可提前取消的
// 无关检测器，并返回支撑该结论的最小决定证据。[VerifyInvariant] 与
// [VerifyEarlyStop] 通过穷举全部剩余结果的补全，核对提前结束不会改变最终判定。
