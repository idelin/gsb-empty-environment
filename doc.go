// Package netsec 提供供网络服务监督器调用的 stack canary 逐字节爆破识别组件。
//
// 带自动重启的服务通过 fork 子进程处理连接。攻击者逐字节猜测 canary 时，
// 每次猜错都会使子进程以相同信号崩溃，且载荷长度随猜测推进逐次增加。
// Detector 消费监督器观察到的子进程退出事件，按来源独立维护
// 「崩溃签名一致 + 载荷长度严格递增（增量不超过 MaxStep）」的连续计数，
// 达到 Threshold 即通过 OnBan 回调请求封禁该来源。
//
// 正常退出不参与也不中断计数，因此成功连接穿插在攻击之间不会掩盖爆破；
// 签名变化、长度不增长或跳跃过大会重置序列，避免把偶发崩溃误判为攻击。
// 所有方法均为并发安全。
