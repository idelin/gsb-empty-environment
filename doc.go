// Package taskpkg 实现供 Go 存储宿主调用的对象能力句柄服务。
//
// 授权模型：
//   - 可信打开 Host.Open 签发能力句柄，绑定对象 ID、版本、租户、
//     能力代次与读写权限；能力字段非导出，宿主外部无法手工伪造。
//   - 数据库文件锁（LockManager）只控制共享/排他冲突，永远不增加权限：
//     持锁者读取时仍须通过能力、租户与代次核对。
//   - Capability.Duplicate 只能收窄权限，对象绑定与能力代次原样继承。
//   - 跨租户移交 Host.Transfer 必须提供源、目标双方真实 Ed25519 签名的
//     目标绑定票据；失败路径不触碰解包缓存、不返回明文。
//   - 对象替换与移交都会推进能力代次，Host.Read 每次读取都重新核对，
//     代次不一致的旧句柄立即失效。
