// Package netsec 提供 Luau 宿主的共享标准库写隔离模拟。
//
// 宿主把同一套标准库与共享元表暴露给多个不可信脚本线程时，必须保证：
//   - 线程全局表是基础环境的代理，代理写入只落线程私有表；
//   - 穿透代理直接写共享表（赋值或 rawset）被拒绝；
//   - 构造期只读的标准库表与共享元表连 setmetatable 也不接受；
//   - getfenv/setfenv 无法取得或改写内置函数闭包所依赖的基础环境；
//   - table.freeze 之后的表进入与只读等效的拒绝写入状态。
//
// 沙箱构造步骤先用 NewTable/AsReadOnly 描述只读标记，用 New 建立各线程
// 全局表对基础环境的代理关系，再把脚本操作序列交给 Execute，最后通过
// Report 检查被拦截事件与被改动的共享表。
