// Package netsec 提供基于 NIST P-256 的 Schnorr 单签与随机化批量验证。
//
// 单签语义
//
// 公钥 P 与签名随机点 R 必须是 65 字节非压缩 SEC1 规范点且非无穷远点，
// 标量 s 必须是 32 字节大端、取值 [1, q-1]（q 为 P-256 群阶）。挑战为
//
//	e = SHA256(固定标签 || P || R || 消息长度 || 消息) mod q
//
// 单验等式为 sG = R + eP。
//
// 批量语义
//
// VerifyBatch 接受 1 至 256 个条目，先拒绝重复的完整 (P,R,s,消息) 条目。
// 随机系数 a_i 由宿主随机 32 字节种子、批次域标签、整批规范转录、索引和
// 大端计数器经 SHA256 mod q 派生，遇到 0 递增计数器，保证 a_i 非零：
//
//	a_i = SHA256(标签 || 种子 || 转录 || BE32(i) || BE32(counter)) mod q
//
// 批量等式为
//
//	Σ a_i s_i G = Σ a_i R_i + Σ a_i e_i P_i
//
// 种子只能来自宿主（默认 crypto/rand），每批新取，调用方不能提供种子；
// 种子缺失或读取失败时整批退回逐份验证。批量成功是概率性接受：仅说明
// 在本批随机系数下等式成立。批量失败后使用同一转录与种子派生的原索引系数
// 递归二分定位；子集通过仅表示该子集在本批随机挑战下通过，叶子一律单验，
// 若父失败而两子均通过则整批退回全部单验，最终返回精确的无效索引。
// Result 记录种子摘要（SHA-256）与整批转录摘要（SHA-256）供审计。
