// Package taskpkg 是供 Go 事件宿主调用的令牌窃取—横向移动检测包。
//
// 待检测的攻击链由三段证据组成：
//  1. 读取令牌（KindTokenRead）：某主体在某设备上读取了一枚令牌；
//  2. 以令牌认证（KindTokenAuth）：另一（或同一）主体在另一（或同一）
//     设备上使用同一枚令牌向服务发起认证；
//  3. 受保护操作（KindProtectedOp）：该认证会话在令牌撤销之后执行操作。
//
// 为防止把不同主体各自的正常事件错误地拼成攻击链，检测器同时要求：
//   - 三段引用的是同一枚令牌，令牌身份由签发者、摘要与代次三者共同标识，
//     任一字段不同即视为不同令牌（例如换发后的新一代令牌）；
//   - 认证主体必须沿受信任的主体派生关系自读取主体可达，且认证设备必须
//     沿受信任的设备派生关系自读取设备可达；主体与设备均携带可信实例号，
//     不同实例号不会被混为一谈；
//   - 受保护操作必须绑定到该次认证（同主体实例、同设备实例、同会话标识）；
//   - 操作必须严格发生在该令牌的撤销事件之后。
//
// 输入时间是偏序而非全序：事件之间只给出已知的“之后于”关系，未被约束的
// 事件可能以任意相对顺序发生。检测器对三段证据的存在性分别给出必然、
// 可能或不成立的结论：
//   - 必然（VerdictCertain）：存在一条三段证据，其每一条所需因果边都已被
//     输入偏序蕴含，即在每个合法拓扑序中该攻击链都成立；
//   - 可能（VerdictPossible）：不存在必然证据，但存在一条三段证据，可以把
//     所需因果边补进偏序而不产生环，即至少存在一个使其成立的合法拓扑序；
//   - 不成立（VerdictNotEstablished）：任何候选证据都与偏序矛盾（补边成环）
//     或不满足同一令牌/派生/绑定/撤销条件，没有任何合法拓扑序能支持攻击。
//
// 判定逻辑与枚举全部合法拓扑序（LinearExtensions）的穷举结果等价：缺少
// 因果边的证据永远只能判“可能”，不会被报为确定攻击。输入事件至多 20 个。
