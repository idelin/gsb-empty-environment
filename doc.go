// Package netsec 提供协议卡死运行的“责任切片”诊断能力。
//
// 它在至多 20 个候选事件上，枚举全部子集并对每个子集做带阻塞语义的具体
// 重放，找出使“所有当前等待仍无法解除”的最小事件子图（等待环的最小消息
// 依赖）。事件涵盖等待资源、生产资源、取消、真实发送与真实接收；一个等待
// 可由候选资源集合中的任意一个生产事件择一满足。
//
// 诊断严格保留事件的真实发生顺序，未选入子集的事件不产生副作用，包内不会
// 重排事件，也不会补造任何消息或资源。每个最小子图都附带完整重放步骤与逐
// 事件移除重放证据，便于 Go 诊断宿主直接核对解释。
