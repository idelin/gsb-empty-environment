// Package netsec 为隐私删除作业提供备份删除证据核验能力。
//
// 备份宿主将不可变备份 DAG、目标数据块引用集合以及删除/不可解密证明
// 交给 Verifier。核验器逐条认证证明并按作用域增量合并，仅当每条备份
// 分支到每个可达目标块的引用都被覆盖时才判定作业完成：
//
//   - 全局作用域证明（Scope == GlobalScope）覆盖该块在所有分支上的引用，
//     仅在宿主确认块及其全部共享副本整体删除/销毁时出具；
//   - 分支作用域证明只覆盖该分支上的引用，共享块不会因一个分支的删除
//     而被当作全局删除；
//   - 未覆盖的 (分支, 目标块) 对会展开为从分支头到目标块的具体路径返回。
//
// 每次报告同时用独立的小图全遍历参考实现（FullScan）枚举全部简单路径，
// 与增量合并结论交叉对照，防止合并状态机与图遍历之间出现偏差。
