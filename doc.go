// Package netsec 提供弱观测条件下的网络扫描序列判定能力。
//
// 采样探针在每个时间段只能观察到部分连接尝试，未被采到的包不能被当作
// “没有发生”。本包把每个时间段的真实情况建模为：已观测目标集合，加上
// 至多给定数量的遗漏目标。所有遗漏补全都必须来自有限目标域，且全序列
// 的遗漏总数不得超过预算。
//
// 判定通过穷举全部合法遗漏补全完成：
//   - 所有合法补全都被扫描模式自动机接受 => 必然发生（输出确定告警）；
//   - 存在接受、也存在拒绝的补全 => 可能发生（证据不足，不告警）；
//   - 所有合法补全都被拒绝 => 不可能发生。
