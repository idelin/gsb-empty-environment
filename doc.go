// Package netsec 为 Go 沙箱宿主提供系统调用过滤器的组合与同步安装能力。
//
// 设计约束：
//   - 过滤器由调用方以纯判定表（[Table]）提供，不含回调或隐藏状态，构造后不可变。
//   - 多个过滤器沿安装顺序组成不可变过滤器链（[Chain]）。组合规则为动作严格度
//     高者胜：终止 > 拒绝 > 通知 > 允许；严格度相同时，后安装者的数据覆盖先安装者。
//   - 因此后安装的“允许”永远无法覆盖早期的“拒绝”。
//   - 线程（[Thread]）共享同一条过滤器链；[Host.Install] 以两阶段方式在全部线程上
//     同步追加，任一线程挂载失败即整体回滚，不留下部分链。
//   - 追加只能收窄最终行为：在调用方给定的有限域（[Domain]）上，若新表会放宽任何
//     键的最终动作，安装在产生任何副作用前失败。
