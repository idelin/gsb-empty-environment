// Package netsec 提供可升级智能合约的存储布局治理组件，供 Go 合约升级服务导入。
//
// 组件围绕“替换实现合约后仍沿用同一存储”的安全问题设计：
//
//   - 升级前核对存储槽位、类型与继承（线性化）顺序，检测布局错位与槽位冲突；
//   - 任何对已使用槽位的布局变更都必须由显式迁移计划覆盖，否则拒绝升级；
//   - 管理员地址与实现地址固定在 EIP-1967 不可冲突的 keccak 命名空间槽位；
//   - 升级执行显式迁移并切换实现槽位，随后回读关键字段做读回验证。
//
// 报告统一使用以下状态，保证不同代码路径解释一致：
//
//   - StateLayoutMisaligned：新布局在已使用槽位上发生字段错位/类型或继承顺序不一致（风险事实，
//     若全部由显式迁移覆盖则升级仍合法；与未迁移并存时升级被阻断）；
//   - StateSlotConflict：同一布局内部槽位重叠，或字段占用 EIP-1967 保留槽位；
//   - StateUnmigratedUpgrade：存在需要迁移的布局变更却没有提供显式迁移；
//   - StateLegalUpgrade：布局兼容且所有变更均被显式迁移覆盖，允许升级；
//   - StateReadbackVerified：升级后关键字段回读值与预期一致（Passed=false 表示回读失败）。
