// Package netsec 为接入服务的解压宿主提供请求级解压预算组件。
//
// 安全目标：发送端可重试失败的压缩片段，但重试无法逃避成本累计。
// 组件对三类实际工作量分别记账——输入读取字节（CostInput）、输出生成
// 字节（CostOutput）、字典操作次数（CostDict）。同一授权请求（相同
// RequestID）的所有失败重试共享同一个 Budget；只有新授权请求才重置。
//
// 解压器通过 Decompressor 步骤接口注入，每步自报实际成本；全部输出先
// 写入宿主隔离缓冲，片段校验（Verifier）通过后才提交副本，校验失败或
// 预算耗尽时输出绝不外泄。预算耗尽后的重试在分配解压器之前即被拒绝，
// 因而 CPU 与内存消耗有确定上界。
