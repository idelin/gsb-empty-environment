// Package netsec 提供安全聚合客户端可导入的份额披露守卫。
//
// 守卫按 广播密钥 -> 分享 -> 掩码输入 -> 一致性签名 -> 解密 五个阶段
// 单向推进，强制执行以下安全不变量：
//   - 掩码输入阶段记录观察到的存活集合 U2；
//   - 一致性阶段要求服务器给出的 U3 是 U2 的子集、|U3| >= 阈值 t，
//     且至少 t 个签名者（均属于 U3）对同一个 U3 给出有效签名；
//   - 解密阶段存活集合 S 必须精确等于已签名的 U3，掉线集合 D 必须
//     精确等于 U2\U3，D 与 S 不得相交；
//   - 同一用户只能披露一种份额，重复索要互斥份额会拒绝并终止会话；
//   - 一次会话只回应一次解密请求，会话终止后不再披露任何份额。
//
// 守卫不持有任何密钥材料，密码学签名校验通过 SignatureVerifier 注入；
// 守卫批准后由调用方按照返回的 Disclosure 清单交出真实份额。
