// Package netsec 提供挂载传播图，供沙箱控制面判断一次挂载/移动更新
// 是否会逃逸到宿主命名空间。
//
// 图中每个 Node 是位于某个挂载命名空间内的挂载实例，带三类传播标记：

//   - Private：私有挂载，事件不外泄；
//   - Shared：共享挂载，事件沿同组共享同伴双向传播，并流入下游从属组；
//   - Slave：从属挂载，只从主组单向接收事件并向下游从属组转发，禁止反向传播。
//
// 传播组之间的从属关系强制保持有向无环（AddGroup/SetMaster 会做环检测）。
// Graph.Propagate 用有限图上的 BFS 重放一次挂载事件，返回所有受影响节点、
// 去重命名空间以及每个节点的最短传播路径，并标记是否宿主可见。
// Replay 在全新图上按序重放事件流，支持 ForbidHostVisible 策略：
// 任何会让宿主可见的更新都被拒绝并回滚，失败事件不改变图状态。
