// Package netsec 提供面向安全事件追踪宿主的伪名化（pseudonymization）组件。
//
// 设计目标：
//   - 跨服务关联仍可使用稳定标识：同一 (租户, 字段类型, 原始值) 在同一密钥代次下
//     永远派生出同一个伪名令牌；
//   - 租户隔离：HMAC 输入以长度前缀方式绑定租户 ID 与字段类型，不同租户的相同邮箱
//     派生出互不相关的令牌，映射表中也不存在跨租户关联；
//   - 密钥换代：密钥环按代次派生域分隔密钥，令牌自带代次，换代批次同时重写事件键
//     与引用，整批验证通过后通过单次原子提交发布旧令牌 -> 新令牌映射；
//   - 显式缺失：批次内无法解析的引用不会被静默丢弃，而以 Missing=true 保留；
//   - 不可逆且不存原文：映射表只保存令牌字符串，原始秘密（如邮箱明文）永不落表。
//
// 典型用法参见 Pseudonymizer、Pseudonymizer.RotateBatch 与 MappingStore。
