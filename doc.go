// Package netsec 提供供 Go 接入宿主（authenticator）调用的 EAP 式状态机。
//
// 企业接入场景中同时存在匿名外层身份与受保护内层身份：
//   - 外层身份仅用于把会话路由到正确的域/策略，绝不成为授权主体；
//   - 内层认证结果由服务器通过三重绑定签发：隧道导出值（exporter）、
//     交换摘要（transcript digest）、物理端口实例（port instance）；
//   - 宿主只在当前端口实例上、且自身中继摘要与服务器摘要一致时才
//     接受成功结果，并通过密钥确认证明对端持有同一隧道导出值。
//
// 因此代理无法把其他会话的内层成功拼接到当前端口：端口重接会生成
// 新的端口实例，使旧绑定立即失效。
