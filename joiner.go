package netsec

import (
	"fmt"
	"unicode/utf8"
)

// joiningType values follow the Joining_Type property used by the ContextJ
// rules in RFC 5892, Appendix A.
type joiningType uint8

const (
	joiningU joiningType = iota
	joiningL
	joiningD
	joiningT
	joiningR
)

const (
	L = joiningL
	D = joiningD
	T = joiningT
	R = joiningR
)

type joiningRange struct {
	lo, hi rune
	typ    joiningType
}

type runeRange struct {
	lo, hi rune
}

// lookupJoiningType returns the Joining_Type of r. Runes not present in the
// table have Joining_Type=U (Non_Joining), which is the Unicode default.
func lookupJoiningType(r rune) joiningType {
	lo, hi := 0, len(joiningTypeRanges)
	for lo < hi {
		mid := int(uint(lo+hi) >> 1)
		entry := joiningTypeRanges[mid]
		switch {
		case r < entry.lo:
			hi = mid
		case r > entry.hi:
			lo = mid + 1
		default:
			return entry.typ
		}
	}
	return joiningU
}

func isVirama(r rune) bool {
	lo, hi := 0, len(viramaRanges)
	for lo < hi {
		mid := int(uint(lo+hi) >> 1)
		entry := viramaRanges[mid]
		switch {
		case r < entry.lo:
			hi = mid
		case r > entry.hi:
			lo = mid + 1
		default:
			return true
		}
	}
	return false
}

// CheckJoinerContext verifies the ContextJ rules for ZERO WIDTH NON-JOINER
// (U+200C) and ZERO WIDTH JOINER (U+200D). A ZWNJ is valid after a virama or
// between a left/dual-joining and a right/dual-joining character. A ZWJ is
// valid only after a virama.
func CheckJoinerContext(label string) error {
	return checkJoiners(label)
}

// ValidateJoiners verifies the ContextJ rules for ZWNJ and ZWJ.
func ValidateJoiners(label string) error {
	return checkJoiners(label)
}

func checkJoiners(label string) error {
	if !utf8.ValidString(label) {
		return &LabelError{Label: label, Code: "P1"}
	}
	if !containsJoiner(label) {
		return nil
	}

	runes := []rune(label)
	for i, r := range runes {
		switch r {
		case '\u200d':
			if i == 0 || !isVirama(runes[i-1]) {
				return &LabelError{Label: label, Code: "C"}
			}
		case '\u200c':
			if i > 0 && isVirama(runes[i-1]) {
				continue
			}
			left := i - 1
			for left >= 0 && lookupJoiningType(runes[left]) == joiningT {
				left--
			}
			if left < 0 {
				return &LabelError{Label: label, Code: "C"}
			}
			leftType := lookupJoiningType(runes[left])
			if leftType != joiningL && leftType != joiningD {
				return &LabelError{Label: label, Code: "C"}
			}
			right := i + 1
			for right < len(runes) && lookupJoiningType(runes[right]) == joiningT {
				right++
			}
			if right >= len(runes) {
				return &LabelError{Label: label, Code: "C"}
			}
			rightType := lookupJoiningType(runes[right])
			if rightType != joiningR && rightType != joiningD {
				return &LabelError{Label: label, Code: "C"}
			}
		}
	}
	return nil
}

func containsJoiner(s string) bool {
	for i := 0; i+2 < len(s); i++ {
		if s[i] == 0xe2 && s[i+1] == 0x80 && (s[i+2] == 0x8c || s[i+2] == 0x8d) {
			return true
		}
	}
	return false
}

// LabelError reports an IDNA label validation failure. Code is the UTS #46
// validity criterion that was violated.
type LabelError struct {
	Label string
	Code  string
}

func (e *LabelError) Error() string {
	return fmt.Sprintf("idna: invalid label %q (%s)", e.Label, e.Code)
}

