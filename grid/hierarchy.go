package grid

import "fmt"

// Parent returns the ancestor of the cell at the given (coarser or equal)
// resolution by truncating hierarchy digits. Pure integer bit manipulation.
func (c Cell) Parent(res int) (Cell, error) {
	if !validRes(res) {
		return 0, ErrInvalidResolution
	}
	if res > c.Res() {
		return 0, fmt.Errorf("%w: parent resolution %d finer than cell resolution %d",
			ErrInvalidResolution, res, c.Res())
	}
	if res == c.Res() {
		return c, nil
	}
	u := uint64(c)
	u &^= 0xF << resShift
	u |= uint64(res) << resShift
	for lvl := res + 1; lvl <= c.Res(); lvl++ {
		shift := 3 * (numDigits - 1 - lvl)
		u &^= 0x7 << shift
		u |= 0x7 << shift
	}
	return Cell(u), nil
}

// IsParentOf reports whether c is a strict ancestor of child.
func (c Cell) IsParentOf(child Cell) bool {
	if c.Face() != child.Face() || c.Res() >= child.Res() {
		return false
	}
	for lvl := 0; lvl <= c.Res(); lvl++ {
		if c.Digit(lvl) != child.Digit(lvl) {
			return false
		}
	}
	return true
}

// Children enumerates all descendants of the cell at the given (finer or
// equal) resolution. The count is 7^(res - c.Res()). Pure integer
// arithmetic: child lattice points are generated by the aperture-7 down
// transforms, no floating point involved.
func (c Cell) Children(res int) ([]Cell, error) {
	if !validRes(res) {
		return nil, ErrInvalidResolution
	}
	if res < c.Res() {
		return nil, fmt.Errorf("%w: children resolution %d coarser than cell resolution %d",
			ErrInvalidResolution, res, c.Res())
	}
	if res == c.Res() {
		return []Cell{c}, nil
	}
	face := c.Face()
	digits := c.digits()
	capHint := 1
	for d := 0; d < res-c.Res(); d++ {
		capHint *= 7
	}
	out := make([]Cell, 0, capHint)
	var rec func(p IJ, level int)
	rec = func(p IJ, level int) {
		if level > res {
			out = append(out, newCell(face, res, digits))
			return
		}
		base := downForLevel(level, p)
		for d := 0; d <= 6; d++ {
			digits[level] = uint8(d)
			rec(base.Add(digitOffsets[d]), level+1)
		}
	}
	rec(c.IJ(), c.Res()+1)
	return out, nil
}
