// Package recovery 为带认证加密的固定帧调度器实现持久恢复策略的
// 判定、最优综合与独立证书验证,供 Go 隔离执行宿主导入使用。
//
// # 公开观察与一致性约束
//
// 恢复决策只能依赖共同公开历史:线路、时隙、帧长、重连请求与关闭结果
// (见 Observation)。秘密任务是否完成属于隐藏状态,不得影响恢复选择。
// 本包把公开历史等价类表示为信念(与该历史相容的隐藏状态集合),综合
// 出的策略是信念到动作的映射,因此在结构上不可能依赖秘密信息。
//
// # 密封纪律
//
// 每次实际密封绑定密钥代次、公开计划、槽号与事务摘要(见 SealRequest)。
// 掉线结果不明时只能取回同一已密封帧(FrameStore.Seal 幂等返回同一
// 密文),不得以同一 nonce 密封另一内容(ErrNonceReuse)。
//
// # 判定与证书
//
// Solve 在信念空间上求解最小-最大可达博弈:宿主提供的不完整持久回执与
// 多个可能线路后继被建模为对抗性非确定转移。若存在在所有相容发送历史
// 中均可完成的公开恢复策略,Solve 返回最小化的最坏额外帧数与可行证书;
// 否则返回对抗陷阱作为不可行证书。Verify 独立校验两类证书,不依赖
// Solve 的内部搜索过程。
