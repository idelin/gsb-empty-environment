// Package matcher 提供基于事件时间的序列规则匹配引擎，供 Go 事件引擎调用。
//
// 规则由以下要素组成：
//   - 事件序列（Rule.Steps）：按顺序匹配的事件段，每段可声明事件类型、时间窗
//     以及是否为否定段（[Step.Negate]）。
//   - 键相等约束（[Rule.EqualKeys]）：要求序列中不同段绑定的事件在给定属性上
//     取值相同。
//   - 时间窗（[Window]）：全部为左闭右开区间 [Low, High)，以零号段事件为锚点
//     或以上一个正段绑定事件为锚点。
//
// 事件时间语义：
//   - 水位线（watermark）单调不回退，调用 [Engine.AdvanceWatermark] 时若出现
//     回退会返回错误。
//   - 事件时间不晚于当前水位线的事件视为迟到事件，引擎拒绝接收并给出原因，
//     拒绝不改变引擎状态。
//   - 否定段不在事件到达时立即下结论：只有当水位线达到该否定段窗口右端（段末）
//     且窗口 [Low, High) 内不存在满足约束的事件时，否定才被确认。
//   - 在否定确认前，已匹配的前缀以“暂定”（[StatusTentative]）状态对外可见；
//     若之后否定窗口内到达了匹配事件，暂定状态被撤销（[StatusRevoked]）。
//   - 正段时间窗在水位线达到右端仍未绑定事件时，匹配实例过期（[StatusExpired]）。
//
// 典型规则“失败登录后十秒没有成功登录，且随后出现管理操作”可表达为三段：
// 失败登录（正段）→ 成功登录（否定段，窗口 [0,10s)）→ 管理操作（正段）。
// 具体构造方式见本包测试。
