export const RFC5054_3072_G = 5n;

export const RFC5054_3072: SrpGroup = Object.freeze({
  name: "RFC 5054 3072-bit group",
  N: RFC5054_3072_N,
  g: RFC5054_3072_G,
  bytes: 384,
});

export const SRP_GROUP_3072 = RFC5054_3072;
export const RFC5054_GROUP_3072 = RFC5054_3072;
export const SRP_N = RFC5054_3072_N;
export const SRP_G = RFC5054_3072_G;

/**
 * SHA-256 is the production default. RFC 5054's original wire format uses
 * SHA-1 and remains available with `{ hash: "sha1" }` for interoperability.
 */
export const DEFAULT_SRP_HASH: SrpHashAlgorithm = "sha256";

export class SrpError extends Error {
  readonly code: string;

  constructor(code: string, message: string) {
    super(message);
    this.name = "SrpError";
    this.code = code;
  }
}

function fail(code: string, message: string): never {
  throw new SrpError(code, message);
}

function isBytes(value: unknown): value is Uint8Array {
  return value instanceof Uint8Array;
}

function toBuffer(value: SrpBytes): Buffer {
  if (typeof value === "string") {
    return Buffer.from(value, "utf8");
  }
  if (!isBytes(value)) {
    fail("INVALID_BYTES", "Expected a string or Uint8Array");
  }
  return Buffer.from(value);
}

function assertGroup(group: SrpGroup): void {
  if (
    !group ||
    typeof group.N !== "bigint" ||
    typeof group.g !== "bigint" ||
    group.N <= 2n ||
    group.g <= 1n ||
    group.g >= group.N ||
    group.bytes < 1
  ) {
    fail("INVALID_GROUP", "Invalid SRP group parameters");
  }
}

export function digest(
  hash: SrpHashAlgorithm,
  ...chunks: Buffer[]
): Buffer {
  const hasher = createHash(hash);
  for (const chunk of chunks) {
    hasher.update(chunk);
  }
  return hasher.digest();
}

export function digestToBigInt(hash: SrpHashAlgorithm, data: Buffer): bigint {
  return BigInt("0x" + data.toString("hex"));
}

export function modPow(base: bigint, exponent: bigint, modulus: bigint): bigint {
  if (modulus <= 0n) {
    fail("INVALID_MODULUS", "Modulus must be positive");
  }
  if (exponent < 0n) {
    fail("INVALID_EXPONENT", "Exponent must not be negative");
  }

  let result = 1n;
  let factor = base % modulus;
  let power = exponent;

  while (power > 0n) {
    if ((power & 1n) === 1n) {
      result = (result * factor) % modulus;
    }
    factor = (factor * factor) % modulus;
    power >>= 1n;
  }

  return result;
}

/**
 * RFC 5054 implicit integer encoding: big-endian, with leading zero bytes
 * stripped. A zero integer is represented by a single zero byte.
 */
export function integerToBytes(value: bigint): Buffer {
  if (value < 0n) {
    fail("INVALID_INTEGER", "Integer must not be negative");
  }
  if (value === 0n) {
    return Buffer.from([0]);
  }

  let hex = value.toString(16);
  if (hex.length % 2 !== 0) {
    hex = "0" + hex;
  }
  return Buffer.from(hex, "hex");
}

/**
 * RFC 5054 PAD(x): the implicit encoding left-padded to the length of N.
 */
export function padInteger(value: bigint, group: SrpGroup = RFC5054_3072): Buffer {
  const encoded = integerToBytes(value);
  if (encoded.length > group.bytes) {
    fail("INTEGER_TOO_LARGE", "Integer does not fit in the SRP group");
  }
  if (encoded.length === group.bytes) {
    return encoded;
  }
  return Buffer.concat([
    Buffer.alloc(group.bytes - encoded.length),
    encoded,
  ]);
}

export function parseBigInt(value: SrpPublicKey): bigint {
  if (typeof value === "bigint") {
    return value;
  }
  if (typeof value === "number") {
    if (!Number.isSafeInteger(value)) {
      fail("INVALID_INTEGER", "Number must be a safe integer");
    }
    return BigInt(value);
  }
  if (typeof value === "string") {
    const text = value.trim();
    if (text.length === 0) {
      fail("INVALID_INTEGER", "Integer string must not be empty");
    }
    if (text.startsWith("-")) {
      fail("INVALID_INTEGER", "Integer must not be negative");
    }
    if (/^0x[0-9a-fA-F]+$/.test(text)) {
      return BigInt(text);
    }
    if (/^[0-9]+$/.test(text)) {
      return BigInt(text);
    }
    if (/^[0-9a-fA-F]+$/.test(text)) {
      return BigInt("0x" + text);
    }
    fail("INVALID_INTEGER", "Unrecognized integer format");
  }
  if (isBytes(value)) {
    if (value.length === 0) {
      return 0n;
    }
    return BigInt("0x" + Buffer.from(value).toString("hex"));
  }
  fail("INVALID_INTEGER", "Expected a bigint, integer string, or byte array");
}

export function computeMultiplier(
  group: SrpGroup = RFC5054_3072,
  hash: SrpHashAlgorithm = DEFAULT_SRP_HASH,
): bigint {
  assertGroup(group);
  return digestToBigInt(
    hash,
    digest(hash, integerToBytes(group.N), padInteger(group.g, group)),
  );
}

export function computeX(
  username: string,
  password: SrpBytes,
  salt: SrpBytes,
  hash: SrpHashAlgorithm = DEFAULT_SRP_HASH,
): bigint {
  const identity = toBuffer(username);
  const passwordBytes = toBuffer(password);
  const saltBytes = toBuffer(salt);
  const inner = digest(hash, identity, Buffer.from(":"), passwordBytes);
  return digestToBigInt(hash, digest(hash, saltBytes, inner));
}

export function deriveVerifier(
  username: string,
  password: SrpBytes,
  salt: SrpBytes,
  options: SrpServerOptions = {},
): bigint {
  const group = options.group ?? RFC5054_3072;
  const hash = options.hash ?? DEFAULT_SRP_HASH;
  assertGroup(group);
  const verifier = modPow(group.g, computeX(username, password, salt, hash), group.N);
  assertVerifier(verifier, group);
  return verifier;
}

export const computeVerifier = deriveVerifier;
export const createVerifier = deriveVerifier;

export function generateSalt(length = 16): Buffer {
  if (!Number.isSafeInteger(length) || length < 1) {
    fail("INVALID_SALT_LENGTH", "Salt length must be a positive integer");
  }
  return nodeRandomBytes(length);
}

export function generateVerifierRecord(
  username: string,
  password: SrpBytes,
  options: SrpServerOptions & { salt?: SrpBytes; saltLength?: number } = {},
): { username: string; salt: Buffer; verifier: bigint } {
  if (typeof username !== "string" || username.length === 0) {
    fail("INVALID_USERNAME", "Username must be a non-empty string");
  }
  const salt =
    options.salt === undefined
      ? generateSalt(options.saltLength ?? 16)
      : toBuffer(options.salt);
  return {
    username,
    salt,
    verifier: deriveVerifier(username, password, salt, options),
  };
}

export function computeU(
  A: bigint,
  B: bigint,
  group: SrpGroup = RFC5054_3072,
  hash: SrpHashAlgorithm = DEFAULT_SRP_HASH,
): bigint {
  return digestToBigInt(
    hash,
    digest(hash, padInteger(A, group), padInteger(B, group)),
  );
}

export function computeSessionKey(
  S: bigint,
  hash: SrpHashAlgorithm = DEFAULT_SRP_HASH,
): Buffer {
  return digest(hash, integerToBytes(S));
}

export function computeM1(
  username: string,
  salt: SrpBytes,
  A: bigint,
  B: bigint,
  K: Buffer,
  group: SrpGroup = RFC5054_3072,
  hash: SrpHashAlgorithm = DEFAULT_SRP_HASH,
): Buffer {
  const hN = digest(hash, integerToBytes(group.N));
  const hG = digest(hash, integerToBytes(group.g));
  const xor = Buffer.alloc(hN.length);
  for (let index = 0; index < hN.length; index += 1) {
    xor[index] = hN[index] ^ hG[index];
  }

  return digest(
    hash,
    xor,
    digest(hash, toBuffer(username)),
    toBuffer(salt),
    integerToBytes(A),
    integerToBytes(B),
    K,
  );
}

export function computeM2(
  A: bigint,
  M1: Buffer,
  K: Buffer,
  hash: SrpHashAlgorithm = DEFAULT_SRP_HASH,
): Buffer {
  return digest(hash, integerToBytes(A), M1, K);
}

export const computeServerProof = computeM2;

export function constantTimeEqual(left: SrpBytes, right: SrpBytes): boolean {
  const leftBytes = toBuffer(left);
  const rightBytes = toBuffer(right);
  if (leftBytes.length !== rightBytes.length) {
    return false;
  }
  return timingSafeEqual(leftBytes, rightBytes);
}

export function validateClientPublicKey(
  clientPublicKey: SrpPublicKey,
  group: SrpGroup = RFC5054_3072,
): bigint {
  const A = parseBigInt(clientPublicKey);

  if (A < 0n) {
    fail("INVALID_A", "Client public key A must not be negative");
  }
  if ((A % group.N) === 0n) {
    fail(
      "INVALID_A_ZERO_MOD_N",
      "Client public key A must not be zero modulo N",
    );
  }
  if (A >= group.N) {
    fail("INVALID_A_RANGE", "Client public key A must be less than N");
  }
  return A;
}

function assertVerifier(verifier: bigint, group: SrpGroup): void {
  if (verifier <= 1n || verifier >= group.N - 1n) {
    fail("INVALID_VERIFIER", "Verifier must be in the range 2..N-2");
  }
}

function assertNonZeroU(u: bigint): void {
  if (u === 0n) {
    fail("ZERO_U", "SRP randomizer u must not be zero");
  }
}

function randomExponent(group: SrpGroup): bigint {
  const raw = nodeRandomBytes(group.bytes);
  const candidate = BigInt("0x" + raw.toString("hex"));
  return (candidate % (group.N - 2n)) + 1n;
}

function computeB(
  verifier: bigint,
  b: bigint,
  group: SrpGroup,
  hash: SrpHashAlgorithm,
): bigint {
  const k = computeMultiplier(group, hash);
  return (k * verifier + modPow(group.g, b, group.N)) % group.N;
}

export class SrpServer {
  readonly username: string;
  readonly salt: Buffer;
  readonly B: bigint;
  readonly Bbytes: Buffer;
  readonly group: SrpGroup;
  readonly hash: SrpHashAlgorithm;

  private readonly verifier: bigint;
  private readonly b: bigint;
  private clientA: bigint | null = null;
  private sessionKey: Buffer | null = null;
  private expectedM1: Buffer | null = null;
  private verifiedProof: SrpServerProof | null = null;

  constructor(
    credentials: SrpServerCredentials,
    options: SrpServerOptions = {},
  ) {
    if (
      !credentials ||
      typeof credentials.username !== "string" ||
      credentials.username.length === 0
    ) {
      fail("INVALID_USERNAME", "Username must be a non-empty string");
    }

    this.group = options.group ?? RFC5054_3072;
    this.hash = options.hash ?? DEFAULT_SRP_HASH;
    assertGroup(this.group);

    this.verifier = parseBigInt(credentials.verifier);
    assertVerifier(this.verifier, this.group);
    this.username = credentials.username;
    this.salt = toBuffer(credentials.salt);

    if (options.b === undefined) {
      let candidateB = 0n;
      do {
        this.b = randomExponent(this.group);
        candidateB = computeB(this.verifier, this.b, this.group, this.hash);
      } while (candidateB === 0n);
      this.B = candidateB;
    } else {
      this.b = parseBigInt(options.b);
      if (this.b <= 0n || this.b >= this.group.N) {
        fail("INVALID_B_PRIVATE", "Server private exponent b is out of range");
      }
      this.B = computeB(this.verifier, this.b, this.group, this.hash);
      if (this.B === 0n) {
        fail("ZERO_B", "Server public key B must not be zero");
      }
    }

    this.Bbytes = padInteger(this.B, this.group);
  }

  get A(): bigint | null {
    return this.clientA;
  }

  get expectedClientProof(): Buffer | null {
    return this.expectedM1;
  }

  get sessionKeyValue(): Buffer {
    if (this.sessionKey === null) {
      fail("SRP_NOT_STARTED", "SRP session has not been started");
    }
    return this.sessionKey;
  }

  challenge(clientPublicKey: SrpPublicKey): SrpServerChallenge {
    if (this.clientA !== null) {
      fail("SRP_ALREADY_STARTED", "SRP session has already been started");
    }

    const A = validateClientPublicKey(clientPublicKey, this.group);
    const u = computeU(A, this.B, this.group, this.hash);
    assertNonZeroU(u);

    const base =
      (A * modPow(this.verifier, u, this.group.N)) % this.group.N;
    const S = modPow(base, this.b, this.group.N);
    const K = computeSessionKey(S, this.hash);
    const M1 = computeM1(
      this.username,
      this.salt,
      A,
      this.B,
      K,
      this.group,
      this.hash,
    );

    this.clientA = A;
    this.sessionKey = K;
    this.expectedM1 = M1;

    return {
      username: this.username,
      salt: this.salt,
      B: this.B,
      Bbytes: this.Bbytes,
    };
  }

  start(clientPublicKey: SrpPublicKey): SrpServerChallenge {
    return this.challenge(clientPublicKey);
  }

  verifyClientProof(clientProof: SrpBytes): SrpServerProof | null {
    if (this.expectedM1 === null || this.clientA === null || this.sessionKey === null) {
      fail("SRP_NOT_STARTED", "Call challenge() before verifying the client proof");
    }

    const proof = toBuffer(clientProof);
    if (!constantTimeEqual(this.expectedM1, proof)) {
      return null;
    }

    if (this.verifiedProof === null) {
      const M2 = computeM2(this.clientA, this.expectedM1, this.sessionKey, this.hash);
      this.verifiedProof = { M2, K: this.sessionKey };
    }
    return this.verifiedProof;
  }

  verifyM1(clientProof: SrpBytes): boolean {
    return this.verifyClientProof(clientProof) !== null;
  }

  getM2(): Buffer {
    if (this.verifiedProof === null) {
      fail("SRP_NOT_VERIFIED", "Client proof has not been verified");
    }
    return this.verifiedProof.M2;
  }
}

export { SrpServer as SrpServerSession };

export function createSrpServer(
  credentials: SrpServerCredentials,
  options: SrpServerOptions = {},
): SrpServer {
  return new SrpServer(credentials, options);
}

export function createServerSession(
  credentials: SrpServerCredentials,
  clientPublicKey: SrpPublicKey,
  options: SrpServerOptions = {},
): { server: SrpServer; challenge: SrpServerChallenge } {
  const server = new SrpServer(credentials, options);
  return { server, challenge: server.challenge(clientPublicKey) };
}

export const createSrpServerSession = createServerSession;
