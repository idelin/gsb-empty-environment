import {
  createHash,
  randomBytes as nodeRandomBytes,
  timingSafeEqual,
} from "node:crypto";

export type SrpHashAlgorithm = "sha1" | "sha256" | "sha384" | "sha512";
export type SrpBytes = Uint8Array | string;
export type SrpPublicKey = bigint | number | string | Uint8Array;

export interface SrpGroup {
  readonly name: string;
  readonly N: bigint;
  readonly g: bigint;
  readonly bytes: number;
}

export interface SrpServerCredentials {
  readonly username: string;
  readonly salt: SrpBytes;
  readonly verifier: bigint;
}

export interface SrpServerOptions {
  readonly group?: SrpGroup;
  readonly hash?: SrpHashAlgorithm;
  /**
   * Only intended for deterministic tests and protocol vectors. Production
   * callers must leave this unset so b is generated by a CSPRNG.
   */
  readonly b?: bigint;
}

export interface SrpServerChallenge {
  readonly username: string;
  readonly salt: Buffer;
  readonly B: bigint;
  readonly Bbytes: Buffer;
}

export interface SrpServerProof {
  readonly M2: Buffer;
  readonly K: Buffer;
}

export interface SrpClientProof {
  readonly M1: Buffer;
  readonly K: Buffer;
}

