// Package dfa 是面向安全启动自定义 VM 的双故障注入分析与最小代价修补组件。
//
// 平台模型
//
// 程序至多 32 条指令，包含 6 个布尔寄存器 r0..r5、1 个模 16 的 4 位计数器
// （inc/dec/jz）、至多 8 个公开输入位 p0..p7，执行步数上限 64。指令覆盖
// inp/lds/and/not/inc/dec/jz/jt/jmp/emit/unlock/halt，其中 lds 读取的验签
// 结果位只读，故障模型不提供任何改写通道。
//
// 故障模型（K=2）
//
// 每个执行步至多注入一次故障，故障种类为：
//   - skip：跳过当前非 halt 指令（halt 不可跳过）；
//   - flip：翻转一个布尔寄存器 r0..r5；
//   - invert：反转一次 jz/jt 条件跳转方向。
//
// 分析能力
//
// 组件提供两份相互独立的可达性检查器：
//   - Attack/SecureAgainstK：基于 (pc, 寄存器, 计数器, 剩余故障数) 记忆化
//     的 BFS，返回步数最浅、故障数最少的攻击见证；
//   - ExhaustiveOracle：无记忆化的故障计划全枚举递归，自带一套独立的
//     单步语义实现。
//
// CrossCheck 同时运行两者并用 Replay 独立重放见证；Analyze 则在排除无
// 故障原漏洞与只读 ROM 禁区后，按总代价升序枚举候选插入点子集，对每个
// 方案同时验证：
//   - 全部无效验签输入上，K<=2 的任何故障轨迹都无法到达 unlock；
//   - 全部有效验签输入上，unlock 次数与完整 emit(tag) 事件序列与原程序
//     逐位一致；
//   - BFS 与全枚举预言机结论一致，攻击见证可被参考 VM 重放复现。
//
// 关键安全结论：单点守卫（SigGuard）以及任何共享单一计数器的关卡都能被
// K=2 击穿；可靠的修补原语是 TripleSigGuard——三道瀑布式串联、各自独立
// 读取只读验签位的守卫，每道都需要一次独立故障才能越过。
