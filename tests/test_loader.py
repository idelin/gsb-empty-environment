import json
import tempfile
import unittest
from pathlib import Path

from buildplanner.loader import InputError, load_packages


def write(tmp, name, **fields):
    payload = {"name": name, "version": "1.0.0"}
    payload.update(fields)
    (Path(tmp) / f"{name}.json").write_text(json.dumps(payload), encoding="utf-8")


class TestLoader(unittest.TestCase):
    def test_roundtrip(self):
        with tempfile.TemporaryDirectory() as tmp:
            write(tmp, "a", version="1.2.3-rc.1", dependencies=["b"],
                  generates=["a.ir"])
            write(tmp, "b", consumes=["a.ir"])
            pkgs = load_packages(tmp)
            self.assertEqual(str(pkgs["a"].version), "1.2.3-rc.1")
            self.assertEqual(pkgs["a"].dependencies, ("b",))
            self.assertEqual(pkgs["b"].consumes, ("a.ir",))

    def test_single_file_list(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "all.json"
            path.write_text(json.dumps([
                {"name": "a", "version": "0.1.0"},
                {"name": "b", "version": "0.2.0", "dependencies": ["a"]},
            ]), encoding="utf-8")
            self.assertEqual(set(load_packages(path)), {"a", "b"})

    def test_unknown_dependency_rejected_no_network(self):
        with tempfile.TemporaryDirectory() as tmp:
            write(tmp, "a", dependencies=["ghost"])
            with self.assertRaisesRegex(InputError, "unknown package 'ghost'"):
                load_packages(tmp)

    def test_duplicate_name_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            (Path(tmp) / "one.json").write_text(
                json.dumps({"name": "dup", "version": "1.0.0"}), encoding="utf-8")
            (Path(tmp) / "two.json").write_text(
                json.dumps({"name": "dup", "version": "2.0.0"}), encoding="utf-8")
            with self.assertRaisesRegex(InputError, "duplicate package name"):
                load_packages(tmp)

    def test_invalid_version_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            write(tmp, "a", version="1.2")
            with self.assertRaisesRegex(InputError, "invalid version"):
                load_packages(tmp)

    def test_unknown_artifact_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            write(tmp, "a", consumes=["nothing.ir"])
            with self.assertRaisesRegex(InputError, "unknown artifact"):
                load_packages(tmp)

    def test_conflicting_generator_rejected(self):
        with tempfile.TemporaryDirectory() as tmp:
            write(tmp, "a", generates=["x.ir"])
            write(tmp, "b", generates=["x.ir"])
            with self.assertRaisesRegex(InputError, "generated by both"):
                load_packages(tmp)


if __name__ == "__main__":
    unittest.main()
