/** 由目标 MPS 概率反查最接近的稳态状态编号（用于静态模型基线） */
export function stateForProbability(pMps: number): { state: number; mps: 0 | 1 } {
  const p = Math.min(Math.max(pMps, 1e-6), 1 - 1e-6);
  const mps: 0 | 1 = p >= 0.5 ? 1 : 0;
  const pLps = 1 - Math.max(p, 1 - p);
  // pLPS(s) = 0.5 * 0.95^s  =>  s = ln(pLPS / 0.5) / ln(0.95)
  const s = Math.round(Math.log(pLps / 0.5) / Math.log(0.95));
  return { state: Math.min(Math.max(s, 0), 62), mps };
}
