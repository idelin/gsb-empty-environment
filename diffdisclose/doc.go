// Package diffdisclose 实现稀疏二叉树上的差分披露组件。
//
// 组件在两棵固定高度的稀疏二叉树（旧树、新树）之间构造唯一且最简的
// 规范证明（canonical proof），向持有旧签名清单的审计客户端披露授权
// 区间内的新增、删除与改变，同时保证：
//
//   - 未变化的叶子不重复披露，可由旧新清单共用的相等同址子树省略；
//   - 未经信任的局部节点缓存只有在其所引用清单、节点地址与摘要全部
//     认证通过后才能用于省略展开；
//   - 已撤回子区间与授权区间外只返回不可解释的整子树摘要，不展开
//     任何键或值，也不透露撤回区间内先前键是否仍存在；
//   - 同一对根、授权集合与已认证缓存只存在一种最简节点序列，验证者
//     重新编码并逐记录检查必要性，拒绝少报删除、空摘要高度挪用与
//     外部缓存冒充。
