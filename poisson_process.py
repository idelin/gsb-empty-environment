"""Exact continuous-time Poisson process simulation.

Events are generated by inverting the cumulative hazard function, never by
discretising time into per-tick Bernoulli trials. Supported intensities:

* homogeneous (constant rate, exponential inter-arrival times),
* piecewise constant (zero-intensity intervals are skipped exactly),
* piecewise linear (non-homogeneous; exact per-interval integrals of the
  intensity with a numerically stable inverse solve).

The random source (a stream of i.i.d. Exp(1) variates) is injected by the
caller. It records its seed and draw count, so runs are replayable: the same
seed reproduces the same event times.

Engine view: each event consumes exactly one Exp(1) variate, and the
cumulative-hazard targets of the events are the cumulative sums of those
variates. The simulator carries the hazard target of the next event and the
hazard integral generated so far across ``generate_*`` calls, so block-wise
generation over adjacent intervals and one-shot generation over their union
consume the identical Exp(1) sequence and produce the same events (event
times agree up to floating-point rounding of equivalent hazard arithmetic;
event counts and draw counts agree exactly). Switching the intensity version
at a time point therefore never resamples existing events.

Convention: every interval is half-open [t_start, t_end). An event whose
hazard target falls exactly on a boundary is emitted once, at the start of
the next interval, so boundaries never produce duplicate events.
"""

from __future__ import annotations

import math
import random
from dataclasses import dataclass
from typing import List, Optional, Sequence, Tuple

__all__ = [
    "ExponentialStream",
    "LinearPiece",
    "PoissonSimulator",
    "SampleRecord",
    "expected_count_homogeneous",
    "expected_count_piecewise_constant",
    "expected_count_piecewise_linear",
]

NEGATIVE_INTENSITY = "negative intensity is not allowed"


class ExponentialStream:
    """Injectable source of i.i.d. Exp(1) variates with replay metadata.

    Records the seed and the number of draws (sample size of the underlying
    random source). Any object with a compatible ``next()`` method (e.g. a
    scripted stream in tests) may be injected into ``PoissonSimulator``
    instead.
    """

    def __init__(self, seed: Optional[object] = None) -> None:
        self.seed = seed
        self._rng = random.Random(seed)
        self.draws = 0

    def next(self) -> float:
        """Return the next Exp(1) variate."""
        self.draws += 1
        # 1 - u lies in (0, 1], so the logarithm is always finite.
        return -math.log(1.0 - self._rng.random())

    def getstate(self) -> object:
        return self._rng.getstate()

    def setstate(self, state: object) -> None:
        self._rng.setstate(state)


@dataclass(frozen=True)
class LinearPiece:
    """Intensity linearly interpolated from lam_start to lam_end on [start, end].

    A constant piece (lam_start == lam_end) covers homogeneous and
    piecewise-constant intensities. Negative intensities are rejected.
    """

    start: float
    end: float
    lam_start: float
    lam_end: float

    def __post_init__(self) -> None:
        if self.end < self.start:
            raise ValueError("piece end must be >= piece start")
        if self.lam_start < 0.0 or self.lam_end < 0.0:
            raise ValueError(NEGATIVE_INTENSITY)

    @property
    def duration(self) -> float:
        return self.end - self.start

    @property
    def hazard(self) -> float:
        """Exact integral of the intensity over this piece (analytic)."""
        return 0.5 * (self.lam_start + self.lam_end) * self.duration

    def invert(self, hazard_from_start: float) -> float:
        """Offset x in [0, duration] whose cumulative hazard equals the argument.

        Solves (slope/2) x^2 + lam_start x - h = 0 with the numerically
        stable form x = 2h / (lam_start + sqrt(lam_start^2 + 2*slope*h)),
        which is exact for slope -> 0 and valid for negative slopes as long
        as h <= self.hazard.
        """
        h = hazard_from_start
        duration = self.duration
        if h <= 0.0 or duration == 0.0:
            return 0.0
        slope = (self.lam_end - self.lam_start) / duration
        if slope == 0.0:
            return h / self.lam_start if self.lam_start > 0.0 else 0.0
        discriminant = self.lam_start * self.lam_start + 2.0 * slope * h
        return (2.0 * h) / (self.lam_start + math.sqrt(discriminant))


@dataclass(frozen=True)
class SampleRecord:
    """Metadata logged for every generation call (seed + sample size)."""

    kind: str
    t_start: float
    t_end: float
    seed: Optional[object]
    n_events: int
    draws_used: int


def _interp(a: float, la: float, b: float, lb: float, t: float) -> float:
    if b == a:
        return la
    return la + (lb - la) * (t - a) / (b - a)


def _linear_pieces(
    knots: Sequence[Tuple[float, float]],
    t_start: Optional[float],
    t_end: Optional[float],
) -> Tuple[List[LinearPiece], float, float]:
    """Build exact linear pieces from knots, clipped to [t_start, t_end]."""
    pts = sorted((float(t), float(lam)) for t, lam in knots)
    if len(pts) < 2:
        raise ValueError("piecewise-linear intensity needs at least 2 knots")
    for _, lam in pts:
        if lam < 0.0:
            raise ValueError(NEGATIVE_INTENSITY)
    t0 = pts[0][0] if t_start is None else float(t_start)
    t1 = pts[-1][0] if t_end is None else float(t_end)
    if t0 > t1:
        raise ValueError("t_start must be <= t_end")
    if t0 < pts[0][0] or t1 > pts[-1][0]:
        raise ValueError("requested range lies outside the knot span")
    pieces: List[LinearPiece] = []
    for (a, la), (b, lb) in zip(pts, pts[1:]):
        lo, hi = max(a, t0), min(b, t1)
        if hi <= lo:
            continue
        pieces.append(
            LinearPiece(lo, hi, _interp(a, la, b, lb, lo), _interp(a, la, b, lb, hi))
        )
    return pieces, t0, t1


def _constant_pieces(
    segments: Sequence[Tuple[float, float, float]],
) -> List[LinearPiece]:
    """Build constant pieces from (start, end, rate) segments; gaps are zero."""
    segs = sorted((float(s), float(e), float(r)) for s, e, r in segments)
    pieces: List[LinearPiece] = []
    prev_end: Optional[float] = None
    for start, end, rate in segs:
        if prev_end is not None and start < prev_end:
            raise ValueError("overlapping segments are not allowed")
        pieces.append(LinearPiece(start, end, rate, rate))
        prev_end = end
    return pieces


# ---------------------------------------------------------------------------
# Analytic expected counts: exact integrals of the intensity, used as the
# reference for empirical estimates. These are EXACT results, not estimates.
# ---------------------------------------------------------------------------

def expected_count_homogeneous(rate: float, t_start: float, t_end: float) -> float:
    """Exact E[N] for a homogeneous process (integral of a constant rate)."""
    if rate < 0.0:
        raise ValueError(NEGATIVE_INTENSITY)
    return rate * (t_end - t_start)


def expected_count_piecewise_constant(
    segments: Sequence[Tuple[float, float, float]],
) -> float:
    """Exact E[N] for piecewise-constant intensity (sum of rate * length)."""
    return sum(piece.hazard for piece in _constant_pieces(segments))


def expected_count_piecewise_linear(
    knots: Sequence[Tuple[float, float]],
    t_start: Optional[float] = None,
    t_end: Optional[float] = None,
) -> float:
    """Exact E[N] for piecewise-linear intensity (trapezoid integrals)."""
    pieces, _, _ = _linear_pieces(knots, t_start, t_end)
    return sum(piece.hazard for piece in pieces)


class PoissonSimulator:
    """Stateful exact simulator driven by an injected Exp(1) stream.

    One Exp(1) variate is consumed per event; event hazard targets are the
    cumulative sums of the variates. State carried across calls:

    * ``_offset``: cumulative hazard integral generated so far,
    * ``_next_target`` / ``_live``: hazard target of the pending event,
    * ``_last_target``: target of the most recently consumed variate.
    """

    def __init__(self, stream: Optional[object] = None, seed: Optional[object] = None) -> None:
        if stream is None:
            stream = ExponentialStream(seed)
        self.stream = stream
        self._offset = 0.0
        self._next_target = 0.0
        self._last_target = 0.0
        self._live = False
        self.history: List[SampleRecord] = []

    # -- core engine ------------------------------------------------------

    def _generate(
        self, pieces: Sequence[LinearPiece], kind: str, t_start: float, t_end: float
    ) -> List[float]:
        events: List[float] = []
        draws_before = self.stream.draws
        cursor = self._offset
        for piece in pieces:
            hazard_end = cursor + piece.hazard
            if piece.hazard > 0.0:
                # Zero-intensity and empty intervals are skipped exactly.
                while True:
                    if not self._live:
                        self._next_target = self._last_target + self.stream.next()
                        self._last_target = self._next_target
                        self._live = True
                    # Strict '<': a target exactly on the boundary is emitted
                    # once, at the start of the next piece.
                    if self._next_target < hazard_end:
                        events.append(
                            piece.start + piece.invert(self._next_target - cursor)
                        )
                        self._live = False
                    else:
                        break
            cursor = hazard_end
        self._offset = cursor
        self.history.append(
            SampleRecord(
                kind=kind,
                t_start=t_start,
                t_end=t_end,
                seed=self.stream.seed,
                n_events=len(events),
                draws_used=self.stream.draws - draws_before,
            )
        )
        return events

    # -- public generators --------------------------------------------------

    def generate_homogeneous(self, rate: float, t_start: float, t_end: float) -> List[float]:
        """Events of a homogeneous process on [t_start, t_end) via Exp(1)/rate."""
        if rate < 0.0:
            raise ValueError(NEGATIVE_INTENSITY)
        return self._generate(
            [LinearPiece(float(t_start), float(t_end), float(rate), float(rate))],
            "homogeneous",
            float(t_start),
            float(t_end),
        )

    def generate_piecewise_constant(
        self, segments: Sequence[Tuple[float, float, float]]
    ) -> List[float]:
        """Events for (start, end, rate) segments; zero-rate gaps are skipped."""
        pieces = _constant_pieces(segments)
        t0 = pieces[0].start if pieces else 0.0
        t1 = pieces[-1].end if pieces else 0.0
        return self._generate(pieces, "piecewise_constant", t0, t1)

    def generate_piecewise_linear(
        self,
        knots: Sequence[Tuple[float, float]],
        t_start: Optional[float] = None,
        t_end: Optional[float] = None,
    ) -> List[float]:
        """Events for a piecewise-linear intensity given by (t, lambda) knots."""
        pieces, t0, t1 = _linear_pieces(knots, t_start, t_end)
        return self._generate(pieces, "piecewise_linear", t0, t1)

    # -- checkpoint / recovery ---------------------------------------------

    def checkpoint(self) -> dict:
        """Snapshot the full state (stream + hazard bookkeeping) for recovery."""
        if not isinstance(self.stream, ExponentialStream):
            raise TypeError("checkpoints require an ExponentialStream")
        return {
            "seed": self.stream.seed,
            "draws": self.stream.draws,
            "rng_state": self.stream.getstate(),
            "offset": self._offset,
            "next_target": self._next_target,
            "last_target": self._last_target,
            "live": self._live,
        }

    @classmethod
    def recover(cls, checkpoint: dict) -> "PoissonSimulator":
        """Restore a simulator from a checkpoint; generation continues exactly."""
        stream = ExponentialStream(checkpoint["seed"])
        stream.setstate(checkpoint["rng_state"])
        stream.draws = checkpoint["draws"]
        sim = cls(stream)
        sim._offset = checkpoint["offset"]
        sim._next_target = checkpoint["next_target"]
        sim._last_target = checkpoint["last_target"]
        sim._live = checkpoint["live"]
        return sim
