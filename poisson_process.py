"""Exact continuous-time Poisson process simulation.

Homogeneous and non-homogeneous Poisson processes with piecewise-linear
intensity, generated by inverting the cumulative hazard against a stream
of unit exponentials.  Event times are exact under the continuous-time
model; no per-tick Bernoulli approximation is used anywhere.

Conventions:
  - intensity is piecewise linear on contiguous segments, always >= 0
    (negative values are rejected);
  - zero-intensity segments are skipped exactly (they contribute no
    hazard and can never produce an event);
  - an event falling exactly on a segment boundary is emitted exactly
    once (it belongs to the segment starting at that boundary);
  - the random source is injected by the caller; the seed and the number
    of draws are recorded so any run is replayable.
"""

from __future__ import annotations

import math
import random
from bisect import bisect_left, bisect_right


class ExpStream:
    """Caller-injected unit-exponential random source.

    Wraps any object providing ``expovariate(lambd)`` (e.g. an instance
    of ``random.Random``).  The seed is stored as metadata and every
    draw is counted, which makes runs auditable and replayable.
    """

    def __init__(self, rng, seed=None):
        if not hasattr(rng, "expovariate"):
            raise TypeError("rng must provide expovariate(lambd)")
        self._rng = rng
        self.seed = seed
        self.draws = 0

    @classmethod
    def from_seed(cls, seed):
        """Build a stream around a fresh ``random.Random(seed)``."""
        return cls(random.Random(seed), seed=seed)

    def draw(self):
        """Draw one Exp(1) sample (counted)."""
        self.draws += 1
        return self._rng.expovariate(1.0)

    def getstate(self):
        getstate = getattr(self._rng, "getstate", None)
        return getstate() if getstate is not None else None

    def setstate(self, state):
        if state is not None:
            self._rng.setstate(state)


class Segment:
    """One linear-intensity segment: lambda(t0 + x) = v0 + slope * x."""

    __slots__ = ("t0", "t1", "v0", "v1")

    def __init__(self, t0, t1, v0, v1):
        if not t1 > t0:
            raise ValueError("segment must have positive width")
        if v0 < 0.0 or v1 < 0.0:
            raise ValueError("negative intensity is not allowed")
        self.t0 = float(t0)
        self.t1 = float(t1)
        self.v0 = float(v0)
        self.v1 = float(v1)

    @property
    def width(self):
        return self.t1 - self.t0

    @property
    def slope(self):
        return (self.v1 - self.v0) / self.width

    def integral(self, x):
        """EXACT hazard accumulated over the first x time units."""
        return self.v0 * x + 0.5 * self.slope * x * x

    @property
    def hazard(self):
        """EXACT total hazard of the segment (analytic integral)."""
        return self.integral(self.width)

    def invert(self, h):
        """Local offset x >= 0 with integral(x) == h.

        Solves (slope/2) x^2 + v0 x - h = 0 for the root in [0, width].
        The form  x = 2h / (v0 + sqrt(v0^2 + 2*slope*h))  avoids the
        catastrophic cancellation of the naive quadratic formula
        (-v0 + sqrt(...)) / slope when |slope| is small, and stays
        well-conditioned for both positive and negative slopes.
        """
        if h <= 0.0:
            return 0.0
        slope = self.slope
        if slope == 0.0:
            # Constant intensity; v0 > 0 because the segment has hazard.
            return h / self.v0
        disc = self.v0 * self.v0 + 2.0 * slope * h
        return (2.0 * h) / (self.v0 + math.sqrt(disc))


class SegmentedIntensity:
    """Piecewise-linear intensity on contiguous segments.

    ``expected_count(t)`` is the analytic integral of the intensity up
    to ``t`` (the cumulative hazard), i.e. the EXACT expected number of
    events on [t_start, t].  ``hazard_to_time`` is its exact inverse.
    """

    def __init__(self, segments):
        if not segments:
            raise ValueError("at least one segment is required")
        self.segments = [Segment(*s) for s in segments]
        for prev, nxt in zip(self.segments, self.segments[1:]):
            if nxt.t0 != prev.t1:
                raise ValueError("segments must be contiguous")
        self.times = [s.t0 for s in self.segments] + [self.segments[-1].t1]
        cumulative = [0.0]
        for seg in self.segments:
            cumulative.append(cumulative[-1] + seg.hazard)
        self.cumulative = cumulative
        self.total_hazard = cumulative[-1]

    @property
    def t_start(self):
        return self.times[0]

    @property
    def t_end(self):
        return self.times[-1]

    def expected_count(self, t=None):
        """EXACT expected event count on [t_start, t] (analytic integral)."""
        if t is None:
            return self.total_hazard
        if t <= self.t_start:
            return 0.0
        if t >= self.t_end:
            return self.total_hazard
        i = bisect_right(self.times, t) - 1
        seg = self.segments[i]
        return self.cumulative[i] + seg.integral(t - seg.t0)

    def hazard_to_time(self, h):
        """Inverse of ``expected_count``: earliest t with cumulative hazard h.

        Zero-hazard segments are skipped exactly; a hazard level that
        lands exactly on a breakpoint maps to that breakpoint (once).
        """
        if h <= 0.0:
            return self.t_start
        if h >= self.total_hazard:
            return self.t_end
        idx = bisect_left(self.cumulative, h, 1)
        if self.cumulative[idx] == h:
            return self.times[idx]
        seg = self.segments[idx - 1]
        return seg.t0 + seg.invert(h - self.cumulative[idx - 1])


def homogeneous(rate, t0, t1):
    """Constant-rate (homogeneous) process on [t0, t1].

    Events are spaced by exact Exp(rate) inter-arrival times, because
    inverting a linear cumulative hazard yields uniform hazard steps.
    """
    return SegmentedIntensity([(t0, t1, rate, rate)])


def piecewise_constant(edges, rates):
    """Piecewise-constant intensity: rates[i] on [edges[i], edges[i+1]).

    Zero-rate intervals are allowed and are skipped exactly.
    """
    if len(edges) != len(rates) + 1:
        raise ValueError("need len(edges) == len(rates) + 1")
    return SegmentedIntensity(
        [(edges[i], edges[i + 1], rates[i], rates[i]) for i in range(len(rates))]
    )


def piecewise_linear(times, values):
    """Continuous piecewise-linear intensity through (times[i], values[i])."""
    if len(times) != len(values) or len(times) < 2:
        raise ValueError("times and values must have equal length >= 2")
    return SegmentedIntensity(
        [(times[i], times[i + 1], values[i], values[i + 1]) for i in range(len(times) - 1)]
    )


class Simulator:
    """Stateful exact event generator.

    Events are produced by mapping a unit-exponential stream through the
    inverse cumulative hazard.  Because the hazard clock is global,
    generating in chunks gives bit-identical results to generating the
    whole horizon at once, and checkpoints resume exactly.
    """

    def __init__(self, intensity, stream):
        self.intensity = intensity
        self.stream = stream
        self._now = intensity.t_start
        self._next_hazard = stream.draw()
        self._hazard_offset = 0.0
        self.emitted = 0

    @property
    def now(self):
        return self._now

    def generate_until(self, t):
        """Return the events in (now, t] and advance the cursor to t.

        EXACT: event times solve Lambda(t) = cumulative Exp(1) sums.
        """
        if t < self._now:
            raise ValueError("cannot generate backwards in time")
        events = []
        while self._next_hazard - self._hazard_offset <= self.intensity.total_hazard:
            te = self.intensity.hazard_to_time(self._next_hazard - self._hazard_offset)
            if te > t:
                break
            events.append(te)
            self.emitted += 1
            self._next_hazard += self.stream.draw()
        self._now = t
        return events

    def switch_intensity(self, new_intensity, at_time=None):
        """Switch to a new intensity version at the current cursor.

        Already emitted events are kept (never resampled); the pending
        exponential remainder is carried onto the new intensity's hazard
        clock.  The global hazard clock is preserved via an offset, so
        the underlying exponential sequence is untouched and the
        continuation is bit-identical to a run on the combined
        piecewise intensity.
        """
        at_time = self._now if at_time is None else at_time
        if at_time != self._now:
            raise ValueError("generate up to the switch time first")
        if not new_intensity.t_start <= at_time <= new_intensity.t_end:
            raise ValueError("switch time outside the new intensity horizon")
        self._hazard_offset += (
            self.intensity.expected_count(self._now)
            - new_intensity.expected_count(at_time)
        )
        self.intensity = new_intensity
        return self

    def checkpoint(self):
        """Snapshot for exact resume (records seed, draws, rng state)."""
        return {
            "seed": self.stream.seed,
            "draws": self.stream.draws,
            "emitted": self.emitted,
            "now": self._now,
            "next_hazard": self._next_hazard,
            "hazard_offset": self._hazard_offset,
            "rng_state": self.stream.getstate(),
        }

    @classmethod
    def restore(cls, intensity, stream, checkpoint):
        """Rebuild a simulator from a checkpoint; replay is exact."""
        stream.setstate(checkpoint["rng_state"])
        stream.draws = checkpoint["draws"]
        sim = cls.__new__(cls)
        sim.intensity = intensity
        sim.stream = stream
        sim._now = checkpoint["now"]
        sim._next_hazard = checkpoint["next_hazard"]
        sim._hazard_offset = checkpoint["hazard_offset"]
        sim.emitted = checkpoint["emitted"]
        return sim
