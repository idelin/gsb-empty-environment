"""Deterministic local fixtures: sample arrays plus a declared sample rate.

No audio device is involved; sources are plain Python lists of floats
generated by closed-form formulas, so tests and examples are exactly
reproducible.
"""

from __future__ import annotations

import math

SAMPLE_RATE = 48_000


def ramp(length: int, start: float = 0.0, step: float = 0.25) -> list[float]:
    return [start + step * i for i in range(length)]


def constant(length: int, value: float = 1.0) -> list[float]:
    return [value] * length


def sine(length: int, freq: float = 440.0, sample_rate: int = SAMPLE_RATE,
         amp: float = 0.8) -> list[float]:
    return [amp * math.sin(2.0 * math.pi * freq * i / sample_rate)
            for i in range(length)]


def make_sources() -> dict[str, list[float]]:
    """A small deterministic source set used by the demo and tests."""
    return {
        "verse": sine(2400, freq=440.0),
        "chorus": sine(1800, freq=660.0),
        "tail": ramp(1200, start=1.0, step=-0.001),
    }
