// Package dictneg 实现压缩字典的带确认协商，供 Go 会话宿主在双向连接上调用。
//
// # 设计目标
//
// 发送端可以替换压缩字典，但字典切换必须经接收端显式确认，确认包丢失后
// 重试不能让两端的字典版本错位。每个字典由其内容的摘要（Digest）唯一标识，
// 数据帧在头部明确绑定字典摘要；接收端对未知摘要的帧只做有界暂存，绝不用
// 其他字典“猜测”解码。
//
// # 三个独立事件
//
// 一次字典安装拆分为三个相互独立、各自可重放的事件：
//
//   - EventInstall：发送端把新字典内容交给接收端落盘；
//   - EventAck / EventNack：接收端确认或拒绝安装，也用于确认启用；
//   - EventEnable：发送端在确认持久化之后，声明此后以哪个摘要编码。
//
// 三个事件都携带单调递增的 Epoch，过期 Epoch 的重放一律丢弃，因此重复投递
// 是幂等的。发送端只有在收到 Ack 后才允许 Enable；接收端只有在收到
// EventEnable 后才切换活动摘要，之前到达的数据帧按各自绑定的摘要分队列
// 有界暂存，启用后按序号重排交付。启用事件同样会被接收端确认；启用或其
// 确认丢失时，重连重放整条安装+启用链即可收敛。
//
// # 失败与重连
//
// 安装失败（摘要不匹配、内容损坏、存储失败等）时发送端保留旧版字典继续
// 工作，活动摘要不发生变化。重连时两端从 Store 读取已持久确认的状态并执行
// 幂等的 Resync：已确认未启用的字典会被重新安装并启用；安装任意阶段掉电，
// 重启后重放事件都能收敛到同一版本。
//
// # 存储
//
// 状态通过 Store 接口持久化。FileStore 以目录形式提供崩溃安全的原子写入，
// 内存实现 MemStore 用于测试。摘要到解压字典的绑定由宿主提供的 Codec 完成，
// 本包不实现具体压缩算法。
