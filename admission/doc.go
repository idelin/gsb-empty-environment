// Package admission 的典型调用顺序如下：
//
//  1. 宿主启动时调用 Host.Bootstrap，传入已认证启动度量、声明树策略、
//     根工作负载名称与初始恢复代次，建立带 Ed25519 签名的信任锚。
//  2. 父工作负载需要创建子节点时，先 Host.PreregisterInstance 预登记实例
//     随机数（支持批内前向引用），再 Host.CheckoutTicket 签出票据。
//     票据绑定父子声明摘要、父子实例随机数、恢复代次、策略版本、用途、
//     卷权限与剩余委托层数，且只能转授父实例已有的权限。
//  3. 延迟请求攒成 Batch 后调用 Host.Submit。提交在比较并替换（CAS）
//     回调内完成：先验签并登记全部节点，再做无环检测、父级解析、
//     权限子集与委托层数校验，最后确认整棵树从已认证根可达。
//     任一检查失败则整批拒绝，不发布实例、不消费票据。
//  4. 回执丢失时，用同一个 Batch 再次调用 Host.Submit 即可按批次摘要
//     取回首次回执，票据不会被重复消费。
//  5. 快照恢复时调用 Host.Restore，恢复代次必须严格递增；旧代次/旧策略
//     票据随即失效，同名工作负载也会获得新的实例随机数。
//  6. 独立审计方调用 VerifySnapshot，仅凭宿主证明公钥、已发布实例和
//     签名收据即可重建并验证完整授权链，不依赖宿主的可变内存状态。
