// Package admission 实现 Go 加载宿主可导入的恢复准入判定。
//
// 背景：主机从旧镜像恢复时只持有片段化的签名更新收据，无法确定两个并行
// 增量哪一个先持久化。本包不猜测持久化顺序，而是枚举所有与检查点相容的
// 历史，对请求区间逐段给出三分类结论：

//   - VerdictExecutable：在每一条相容历史中，该位置都是同一可信内容，
//     且每一条历史都保留了所需（执行）权限。
//   - VerdictForbidden：在每一条相容历史中该位置都缺所需权限，执行必然
//     被拒绝，与内容无关。
//   - VerdictUnknown：历史间存在分歧（内容不同、可信性不同），无法给出
//     确定结论，宿主必须保守处理。
//
// 核心不变量：
//
//   - 更新收据（无论内容型还是仅收紧权限型）都绑定发布者、旧根、新根
//     和作用页区间，收据沿旧根/新根构成更新 DAG。
//   - 内容以摘要标识，别名页可以共享同一摘要；但权限是映像位置的属性，
//     收紧权限只作用于被声明的位置区间，不随摘要传播。
//   - 每条历史从检查点独立重放，跨历史结论只在完整的位置状态之间比较，
//     因此不可能把一条历史的可信内容与另一条历史的签名/权限范围拼接成
//     一个“确定可执行”的结果。
//   - 页号为 48 位。所有状态与判定都用有序区间（边界列表）表示，
//     复杂度只与收据和分片的边界数量相关，从不按页展开。
//   - 分片边界由宿主提供并被强制校验：必须有序、首尾相接、完整覆盖
//     [0, 2^48)；内容收据的作用区间必须由完整分片拼成。
//
// ReferenceAdmit 是仅供小地址域测试使用的独立逐页参考实现，可与
// Build/Admit 的区间实现做全历史对照。
