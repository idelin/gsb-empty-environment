"""Load package build inputs from local JSON files. No network access.

Each package JSON object:
{
  "name": "core",
  "version": "1.2.3-alpha.1",        # major.minor.patch[-prerelease]
  "dependencies": ["base"],          # names of other local packages
  "generates": ["core.ir"],          # artifacts this package produces
  "consumes": ["base.ir"]            # artifacts this package needs as input
}
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

from .semver import Version, VersionError


class InputError(ValueError):
    """Raised when the local JSON build input is invalid."""


@dataclass(frozen=True)
class Package:
    name: str
    version: Version
    dependencies: tuple[str, ...] = ()
    generates: tuple[str, ...] = ()
    consumes: tuple[str, ...] = ()
    source: str = ""

    @property
    def label(self) -> str:
        return f"{self.name}@{self.version}"


def _parse_package(raw: object, source: str) -> Package:
    if not isinstance(raw, dict):
        raise InputError(f"{source}: package entry must be a JSON object")
    name = raw.get("name")
    if not isinstance(name, str) or not name:
        raise InputError(f"{source}: 'name' must be a non-empty string")
    if "version" not in raw:
        raise InputError(f"{source}: package {name!r} is missing 'version'")
    try:
        version = Version.parse(raw["version"])
    except VersionError as exc:
        raise InputError(f"{source}: package {name!r}: {exc}") from exc

    def _str_list(key: str) -> tuple[str, ...]:
        value = raw.get(key, [])
        if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
            raise InputError(
                f"{source}: package {name!r}: {key!r} must be a list of strings"
            )
        return tuple(value)

    return Package(
        name=name,
        version=version,
        dependencies=_str_list("dependencies"),
        generates=_str_list("generates"),
        consumes=_str_list("consumes"),
        source=source,
    )


def _read_json(path: Path) -> object:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise InputError(f"{path}: invalid JSON: {exc}") from exc
    except OSError as exc:
        raise InputError(f"{path}: cannot read: {exc}") from exc


def load_packages(path: str | Path) -> dict[str, Package]:
    """Load packages from a directory of *.json files or one JSON file.

    A single file may contain either one package object or a list of them.
    """
    root = Path(path)
    raws: list[tuple[object, str]] = []
    if root.is_dir():
        files = sorted(root.glob("*.json"))
        if not files:
            raise InputError(f"{root}: no *.json package files found")
        for file in files:
            raws.append((_read_json(file), str(file)))
    elif root.is_file():
        raws.append((_read_json(root), str(root)))
    else:
        raise InputError(f"{root}: no such file or directory")

    packages: dict[str, Package] = {}
    for raw, source in raws:
        entries = raw if isinstance(raw, list) else [raw]
        for entry in entries:
            pkg = _parse_package(entry, source)
            if pkg.name in packages:
                raise InputError(
                    f"duplicate package name {pkg.name!r} "
                    f"({packages[pkg.name].source} and {source})"
                )
            packages[pkg.name] = pkg

    for pkg in packages.values():
        for dep in pkg.dependencies:
            if dep not in packages:
                raise InputError(
                    f"{pkg.source}: package {pkg.name!r} depends on unknown "
                    f"package {dep!r}; only local packages are resolvable "
                    "(no network lookup)"
                )
    artifacts: dict[str, str] = {}
    for pkg in packages.values():
        for artifact in pkg.generates:
            if artifact in artifacts:
                raise InputError(
                    f"artifact {artifact!r} generated by both "
                    f"{artifacts[artifact]!r} and {pkg.name!r}"
                )
            artifacts[artifact] = pkg.name
    for pkg in packages.values():
        for artifact in pkg.consumes:
            if artifact not in artifacts:
                raise InputError(
                    f"{pkg.source}: package {pkg.name!r} consumes unknown "
                    f"artifact {artifact!r}"
                )
    return packages
