"""Build the staged co-compilation plan.

Semantics:
- Declared dependencies form the compile graph. Its strongly connected
  components are co-compilation groups: a cyclic group is compiled together
  as one unit, and its internal member order is NOT a topological order.
- A generator emits its artifacts at the END of its stage; a consumer needs
  them at the START of its stage. An artifact edge consumer -> generator is
  therefore only satisfiable when stage(generator) < stage(consumer).
  If the declared-dependency staging forces stage(generator) >=
  stage(consumer), the generator (transitively) depends on its own output:
  a forbidden cross-stage cycle. It is rejected with concrete evidence, and
  only the affected groups are blocked; unrelated groups keep an executable
  plan.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from .graph import condensation_stages, shortest_path, tarjan_scc
from .loader import Package


@dataclass(frozen=True)
class Group:
    id: int
    members: tuple[str, ...]
    stage: int
    cyclic: bool

    @property
    def internal_order(self) -> str:
        if self.cyclic:
            return "unordered (cycle: compile together, no topological order)"
        return "trivial (single package)"


@dataclass(frozen=True)
class CrossStageCycle:
    artifact: str
    generator: str
    generator_stage: int
    consumer: str
    consumer_stage: int
    dependency_path: tuple[str, ...]

    def describe(self, packages: dict[str, Package]) -> str:
        def lbl(name: str) -> str:
            return packages[name].label

        path = " -> ".join(lbl(n) for n in self.dependency_path)
        return (
            f"cross-stage cycle on artifact {self.artifact!r}: "
            f"generator {lbl(self.generator)} (stage {self.generator_stage}) "
            f"emits {self.artifact!r} only at the end of its stage, but "
            f"consumer {lbl(self.consumer)} (stage {self.consumer_stage}) "
            f"needs it at the start of an earlier-or-equal stage. "
            f"Cycle: {path} -[consumes {self.artifact!r} generated by]-> "
            f"{lbl(self.generator)}"
        )


@dataclass
class Plan:
    groups: list[Group]
    stages: list[list[int]]  # stage index -> group ids
    cycles: list[CrossStageCycle]
    blocked_groups: set[int]
    executable_groups: set[int]

    @property
    def ok(self) -> bool:
        return not self.cycles


def build_plan(packages: dict[str, Package]) -> Plan:
    names = sorted(packages)
    dep_edges = {name: sorted(packages[name].dependencies) for name in names}

    components = tarjan_scc(names, dep_edges)
    stages_of = condensation_stages(components, dep_edges)
    groups = [
        Group(
            id=idx,
            members=tuple(comp),
            stage=stages_of[idx],
            cyclic=len(comp) > 1
            or (len(comp) == 1 and comp[0] in dep_edges[comp[0]]),
        )
        for idx, comp in enumerate(components)
    ]
    group_of: dict[str, int] = {}
    for group in groups:
        for member in group.members:
            group_of[member] = group.id

    num_stages = max((g.stage for g in groups), default=-1) + 1
    stages: list[list[int]] = [[] for _ in range(num_stages)]
    for group in groups:
        stages[group.stage].append(group.id)

    # Artifact flow: consumer -> generator. Must point strictly backward
    # across stages (generator in an earlier stage than the consumer).
    artifact_owner: dict[str, str] = {}
    for pkg in packages.values():
        for artifact in pkg.generates:
            artifact_owner[artifact] = pkg.name

    cycles: list[CrossStageCycle] = []
    for pkg in packages.values():
        for artifact in pkg.consumes:
            generator = artifact_owner[artifact]
            if generator == pkg.name:
                gen_group = group_of[generator]
                cycles.append(
                    CrossStageCycle(
                        artifact=artifact,
                        generator=generator,
                        generator_stage=groups[gen_group].stage,
                        consumer=pkg.name,
                        consumer_stage=groups[gen_group].stage,
                        dependency_path=(generator,),
                    )
                )
                continue
            gen_stage = groups[group_of[generator]].stage
            con_stage = groups[group_of[pkg.name]].stage
            if gen_stage >= con_stage:
                path = shortest_path(dep_edges, generator, pkg.name)
                if path is None:
                    path = [generator, pkg.name]
                cycles.append(
                    CrossStageCycle(
                        artifact=artifact,
                        generator=generator,
                        generator_stage=gen_stage,
                        consumer=pkg.name,
                        consumer_stage=con_stage,
                        dependency_path=tuple(path),
                    )
                )

    # Block the groups involved in cycles and everything that depends on them.
    blocked: set[int] = set()
    for cycle in cycles:
        blocked.add(group_of[cycle.generator])
        blocked.add(group_of[cycle.consumer])
    changed = True
    while changed:
        changed = False
        for group in groups:
            if group.id in blocked:
                continue
            for member in group.members:
                if any(group_of[d] in blocked for d in dep_edges[member]):
                    blocked.add(group.id)
                    changed = True
                    break

    executable = {g.id for g in groups} - blocked
    return Plan(
        groups=groups,
        stages=stages,
        cycles=cycles,
        blocked_groups=blocked,
        executable_groups=executable,
    )


def render_plan(packages: dict[str, Package], plan: Plan) -> str:
    lines: list[str] = []
    for stage_idx, group_ids in enumerate(plan.stages):
        lines.append(f"stage {stage_idx}:")
        for gid in group_ids:
            group = plan.groups[gid]
            status = "BLOCKED" if gid in plan.blocked_groups else "executable"
            members = ", ".join(packages[m].label for m in group.members)
            lines.append(
                f"  group g{gid} [{status}] ({group.internal_order}): {members}"
            )
    if plan.cycles:
        lines.append("blocking evidence:")
        for cycle in plan.cycles:
            lines.append(f"  - {cycle.describe(packages)}")
    return "\n".join(lines)
